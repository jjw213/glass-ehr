-- 사내 메시지 (#80). Node HR_THREADS·HR_MESSAGES 를 대신한다(HR_ 테이블은 Spring 에서 쓰지 않는다).
--
-- 규칙
--   - 참여자는 사원(employee.emp_id) 기준이다. 사원과 연결되지 않은 계정(시스템 관리자 등)은 대화에 참여하지 않는다.
--   - 메시지는 추가만 한다(수정·삭제 API 없음). 본문은 앞뒤 공백을 뺀 뒤 1~1000자(앱이 검사, DB 도 1000자 제한).
--   - 읽음은 메시지마다 읽은 사원과 시각을 남긴다(msg_read). 안 읽은 수 = 남이 보낸 메시지 중 내 읽음 행이 없는 것.
--   - 법령 수치 계산 없음.
-- 조회·저장: com.glassehr.message.MessageRepository (JdbcTemplate)

-- 대화방
CREATE TABLE msg_thread (
    thread_id    NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at   TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_msg_thread PRIMARY KEY (thread_id)
);

-- 참여자
CREATE TABLE msg_thread_member (
    thread_id    NUMBER(15)    NOT NULL,
    emp_id       NUMBER(10)    NOT NULL,
    joined_at    TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_msg_thread_member PRIMARY KEY (thread_id, emp_id),
    CONSTRAINT fk_msg_member_thread FOREIGN KEY (thread_id) REFERENCES msg_thread (thread_id),
    CONSTRAINT fk_msg_member_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id)
);

CREATE INDEX ix_msg_member_emp ON msg_thread_member (emp_id);

-- 메시지. 보낸 사람은 그 대화방 참여자여야 한다(FK 로 강제).
CREATE TABLE msg_message (
    message_id       NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    thread_id        NUMBER(15)          NOT NULL,
    sender_emp_id    NUMBER(10)          NOT NULL,
    body             VARCHAR2(1000 CHAR) NOT NULL,
    sent_at          TIMESTAMP(6)        NOT NULL,

    CONSTRAINT pk_msg_message PRIMARY KEY (message_id),
    CONSTRAINT fk_msg_message_member FOREIGN KEY (thread_id, sender_emp_id)
        REFERENCES msg_thread_member (thread_id, emp_id),
    CONSTRAINT ck_msg_message_body CHECK (LENGTH(TRIM(body)) > 0)
);

CREATE INDEX ix_msg_message_thread ON msg_message (thread_id, message_id);

-- 읽음. 읽은 사람은 그 대화방 참여자여야 한다.
CREATE TABLE msg_read (
    message_id   NUMBER(15)    NOT NULL,
    thread_id    NUMBER(15)    NOT NULL,
    emp_id       NUMBER(10)    NOT NULL,
    read_at      TIMESTAMP(6)  NOT NULL,

    CONSTRAINT pk_msg_read PRIMARY KEY (message_id, emp_id),
    CONSTRAINT fk_msg_read_message FOREIGN KEY (message_id) REFERENCES msg_message (message_id),
    CONSTRAINT fk_msg_read_member FOREIGN KEY (thread_id, emp_id) REFERENCES msg_thread_member (thread_id, emp_id)
);

CREATE INDEX ix_msg_read_member ON msg_read (thread_id, emp_id);
