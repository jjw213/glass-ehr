-- 로그인·세션과 접속기록 (#76). 설계: docs/auth-design.md 8장
--
-- 근거
--   - 개인정보 보호법 제29조(안전조치의무)와 개인정보의 안전성 확보조치 기준(고시)의 접근 통제(인증 실패 시 접근 제한)·
--     접속기록 보관. 조항 번호·보관 기간은 docs/auth-design.md 8장에 확인 결과를 적는다.
--     이 마이그레이션은 보관 기간을 정하지 않고, 로그를 지우는 기능도 두지 않는다(보관·파기는 별도 이슈).
--   - 로그인 실패 허용 횟수와 잠금 시간은 법정 수치가 아니라 운영 설정(glassehr.auth.*)이다.
--
-- 규칙
--   - 비밀번호는 원문을 저장하지 않는다. password_hash 는 BCrypt 문자열($2a$/$2b$/$2y$, 60자)만 받는다.
--     비어 있으면 그 계정은 로그인할 수 없다(데모 계정 비밀번호는 .env 값으로 앱이 해시해 넣는다, DemoAccountSeeder).
--   - 접속기록(login_access_log)은 추가만 한다(엔티티 @Immutable, 삭제 API 없음). 비밀번호는 남기지 않는다.
--     없는 아이디로 시도한 기록도 남겨야 하므로 app_user FK 를 걸지 않는다.
--   - 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.auth.AppUser, LoginAccessLog (ddl-auto: validate)

ALTER TABLE app_user ADD (
    password_hash        VARCHAR2(100 CHAR),
    password_changed_at  TIMESTAMP(6),
    failed_login_count   NUMBER(5)    DEFAULT 0 NOT NULL,
    locked_until         TIMESTAMP(6)
);

ALTER TABLE app_user ADD CONSTRAINT ck_app_user_pw_hash
    CHECK (password_hash IS NULL OR REGEXP_LIKE(password_hash, '^\$2[aby]\$[0-9][0-9]\$', 'c'));
ALTER TABLE app_user ADD CONSTRAINT ck_app_user_pw_changed
    CHECK (password_hash IS NULL OR password_changed_at IS NOT NULL);
ALTER TABLE app_user ADD CONSTRAINT ck_app_user_failed_count CHECK (failed_login_count >= 0);

-- 로그인·로그아웃 접속기록.
--   event_code   LOGIN_SUCCESS, LOGIN_FAILURE, LOGOUT
--   fail_reason  LOGIN_FAILURE 일 때만: UNKNOWN_USER(없는 아이디), BAD_PASSWORD, LOCKED(잠긴 동안 시도),
--                INACTIVE(사용 중지), NO_PASSWORD(비밀번호 미설정)
--   locked_yn    이 실패로 계정이 잠겼으면 Y
--   login_id     시도한 아이디(50자까지). 없는 아이디도 남긴다.
CREATE TABLE login_access_log (
    log_id        NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    login_id      VARCHAR2(50 CHAR)   NOT NULL,
    event_code    VARCHAR2(20 CHAR)   NOT NULL,
    fail_reason   VARCHAR2(20 CHAR),
    locked_yn     CHAR(1)             DEFAULT 'N' NOT NULL,
    client_ip     VARCHAR2(45 CHAR),
    occurred_at   TIMESTAMP(6)        NOT NULL,

    CONSTRAINT pk_login_access_log PRIMARY KEY (log_id),
    CONSTRAINT ck_login_log_event CHECK (event_code IN ('LOGIN_SUCCESS', 'LOGIN_FAILURE', 'LOGOUT')),
    CONSTRAINT ck_login_log_reason CHECK (
        (event_code = 'LOGIN_FAILURE' AND fail_reason IN ('UNKNOWN_USER', 'BAD_PASSWORD', 'LOCKED', 'INACTIVE', 'NO_PASSWORD'))
        OR (event_code <> 'LOGIN_FAILURE' AND fail_reason IS NULL)),
    CONSTRAINT ck_login_log_locked CHECK (locked_yn IN ('Y', 'N') AND (locked_yn = 'N' OR event_code = 'LOGIN_FAILURE'))
);

CREATE INDEX ix_login_log_at ON login_access_log (occurred_at);
CREATE INDEX ix_login_log_user ON login_access_log (login_id, occurred_at);

-- Spring Session JDBC 세션 저장소(#75 결정). spring-session-jdbc 3.5 의 schema-oracle.sql 과 같은 구조다.
-- 앱은 이 테이블을 만들지 않는다(spring.session.jdbc.initialize-schema: never).
-- PRINCIPAL_NAME 에는 로그인 아이디가 들어간다(사용 중지 시 그 사용자 세션을 찾아 끊는 경로용).
CREATE TABLE SPRING_SESSION (
    PRIMARY_ID             CHAR(36)            NOT NULL,
    SESSION_ID             CHAR(36)            NOT NULL,
    CREATION_TIME          NUMBER(19,0)        NOT NULL,
    LAST_ACCESS_TIME       NUMBER(19,0)        NOT NULL,
    MAX_INACTIVE_INTERVAL  NUMBER(10,0)        NOT NULL,
    EXPIRY_TIME            NUMBER(19,0)        NOT NULL,
    PRINCIPAL_NAME         VARCHAR2(100 CHAR),
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID  CHAR(36)            NOT NULL,
    ATTRIBUTE_NAME      VARCHAR2(200 CHAR)  NOT NULL,
    ATTRIBUTE_BYTES     BLOB                NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES SPRING_SESSION (PRIMARY_ID) ON DELETE CASCADE
);
