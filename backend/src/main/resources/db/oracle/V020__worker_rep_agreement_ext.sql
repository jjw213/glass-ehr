-- 근로자대표 서면합의서 관리 (#27). 설계: docs/labor-agreement-design.md
--
-- #26(V017)이 휴일 대체용으로 처음 만든 worker_rep_agreement 를 서면합의가 전제인 모든 제도로 넓힌다.
-- 휴일 대체(holiday.agreement_id FK)는 그대로 이 테이블을 가리킨다.
--
-- 규칙
--   - agreement_kind: 서면합의가 전제인 제도. 값과 근거 조문은 com.glassehr.attendance.AgreementType 과 같다
--     (LaborAgreementSchemaScriptTest).
--   - 유효기간 저장은 V017 그대로 [effective_from, effective_to) (effective_to = 마지막 유효일의 다음 날, NULL = 기한 없음).
--     API·화면은 합의서에 적힌 대로 마지막 유효일(validUntil = effective_to - 1일)로 주고받는다.
--   - 대상 범위: scope_type ALL(회사 전체) 또는 SITE(사업장 한 곳, scope_site_code). target_desc 는 합의서에 적힌
--     대상 근로자 범위(업무·직군 등)를 옮긴 글이다. #26 때 등록된 행은 비어 있을 수 있어 DB 는 NULL 을 허용하고,
--     새로 등록·수정할 때는 서비스가 필수로 검사한다.
--   - 근로자대표(근로기준법 제24조 제3항): MAJORITY_UNION(근로자 과반수로 조직된 노동조합) 이면 rep_union_name,
--     MAJORITY_REP(근로자 과반수를 대표하는 자) 이면 rep_emp_id(사원 참조). 사람 이름은 따로 적지 않는다.
--   - 첨부파일은 worker_rep_agreement_file 에 BLOB 으로 둔다(별도 파일 저장소 없음). 확인용 SHA-256 을 함께 저장한다.
--   - 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.attendance.LaborAgreement, LaborAgreementFile (ddl-auto: validate)

ALTER TABLE worker_rep_agreement DROP CONSTRAINT ck_wra_kind;

ALTER TABLE worker_rep_agreement ADD CONSTRAINT ck_wra_kind
    CHECK (agreement_kind IN ('FLEXIBLE_WRITTEN', 'FLEXIBLE_LONG', 'SELECTIVE', 'HOLIDAY_SUBSTITUTION',
                              'COMPENSATORY_LEAVE', 'DISCRETIONARY', 'ANNUAL_LEAVE_SUBSTITUTE'));

-- Oracle 에서 공백만 있는 문자열의 TRIM 결과는 NULL 이라 V017 의 LENGTH(TRIM(x)) > 0 은 공백을 막지 못한다(#65 와 같은 문제).
-- 이 이슈부터 제목·문서 참조를 수정할 수 있으므로 TRIM(x) IS NOT NULL 로 바꾼다.
ALTER TABLE worker_rep_agreement DROP CONSTRAINT ck_wra_title;
ALTER TABLE worker_rep_agreement DROP CONSTRAINT ck_wra_document;
ALTER TABLE worker_rep_agreement ADD CONSTRAINT ck_wra_title CHECK (TRIM(title) IS NOT NULL);
ALTER TABLE worker_rep_agreement ADD CONSTRAINT ck_wra_document CHECK (TRIM(document_ref) IS NOT NULL);

ALTER TABLE worker_rep_agreement ADD (
    scope_type     VARCHAR2(10 CHAR)   DEFAULT 'ALL' NOT NULL,
    scope_site_code VARCHAR2(3 CHAR),
    target_desc     VARCHAR2(1000 CHAR),
    rep_union_name  VARCHAR2(200 CHAR),
    rep_emp_id      NUMBER(10),
    updated_by      VARCHAR2(50 CHAR),
    updated_at      TIMESTAMP(6)
);

UPDATE worker_rep_agreement SET updated_by = created_by, updated_at = created_at;

ALTER TABLE worker_rep_agreement MODIFY (
    updated_by NOT NULL,
    updated_at DEFAULT SYSTIMESTAMP NOT NULL
);

ALTER TABLE worker_rep_agreement ADD (
    CONSTRAINT fk_wra_site
        FOREIGN KEY (scope_site_code) REFERENCES biz_site (site_code),
    CONSTRAINT fk_wra_rep_emp
        FOREIGN KEY (rep_emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_wra_scope
        CHECK ((scope_type = 'ALL' AND scope_site_code IS NULL)
            OR (scope_type = 'SITE' AND scope_site_code IS NOT NULL)),
    CONSTRAINT ck_wra_target
        CHECK (target_desc IS NULL OR TRIM(target_desc) IS NOT NULL),
    CONSTRAINT ck_wra_rep
        CHECK ((rep_type = 'MAJORITY_UNION' AND rep_emp_id IS NULL
                AND (rep_union_name IS NULL OR TRIM(rep_union_name) IS NOT NULL))
            OR (rep_type = 'MAJORITY_REP' AND rep_union_name IS NULL))
);

CREATE INDEX ix_wra_kind ON worker_rep_agreement (agreement_kind, effective_from);
CREATE INDEX ix_wra_effective_to ON worker_rep_agreement (effective_to);
CREATE INDEX ix_wra_rep_emp ON worker_rep_agreement (rep_emp_id);

CREATE TABLE worker_rep_agreement_file (
    file_id       NUMBER(12) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    agreement_id  NUMBER(10)          NOT NULL,
    file_name     VARCHAR2(255 CHAR)  NOT NULL,
    content_type  VARCHAR2(100 CHAR)  NOT NULL,
    file_size     NUMBER(12)          NOT NULL,
    sha256        VARCHAR2(64 CHAR)   NOT NULL,
    content       BLOB                NOT NULL,
    uploaded_by   VARCHAR2(50 CHAR)   NOT NULL,
    uploaded_at   TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_wra_file PRIMARY KEY (file_id),
    CONSTRAINT fk_wra_file_agreement
        FOREIGN KEY (agreement_id) REFERENCES worker_rep_agreement (agreement_id),
    CONSTRAINT ck_wra_file_name
        CHECK (TRIM(file_name) IS NOT NULL),
    CONSTRAINT ck_wra_file_size
        CHECK (file_size > 0),
    CONSTRAINT ck_wra_file_sha
        CHECK (REGEXP_LIKE(sha256, '^[0-9a-f]+$', 'c') AND LENGTH(sha256) = 64)
);

CREATE INDEX ix_wra_file_agreement ON worker_rep_agreement_file (agreement_id);
