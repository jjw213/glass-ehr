-- 유연근무제 배정과 근무계획 (#38). 설계: docs/flexible-work-design.md.
--
-- flex_work_assign: 사원별 유연근무제 적용 단위(단위기간·정산기간 한 번).
--   - work_system: FLEXIBLE_SHORT(근로기준법 제51조 제1항, 취업규칙), FLEXIBLE_WRITTEN(제51조 제2항),
--     FLEXIBLE_LONG(제51조의2), SELECTIVE(제52조), DISCRETIONARY(제58조 제3항)
--   - 서면합의가 전제인 제도(FLEXIBLE_SHORT 제외)는 agreement_id 가 반드시 있어야 한다.
--     합의서가 기간 전체를 덮는지는 LaborAgreementGuard 가 저장 전에 검사한다(422).
--   - 법정 한도(단위기간·상한·휴식)는 legal_rate(V028 항목) 값으로 서비스가 검사한다. 여기에는 수치를 두지 않는다.
-- flex_work_plan: 탄력적은 사용자가 정한 날별 근로시간 계획, 선택적은 사원이 입력한 날별 시업·종업 계획.

CREATE TABLE flex_work_assign (
    flex_id        NUMBER(12) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id         NUMBER(10)         NOT NULL,
    work_system    VARCHAR2(20 CHAR)  NOT NULL,
    period_start   DATE               NOT NULL,
    period_end     DATE               NOT NULL,
    job_code       VARCHAR2(30 CHAR),
    core_start_min NUMBER(4),
    core_end_min   NUMBER(4),
    deemed_minutes NUMBER(5),
    agreement_id   NUMBER(12),
    note           VARCHAR2(500 CHAR),
    created_by     VARCHAR2(50 CHAR)  NOT NULL,
    created_at     TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_flex_work_assign PRIMARY KEY (flex_id),
    CONSTRAINT fk_flex_work_assign_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT fk_flex_work_assign_agreement
        FOREIGN KEY (agreement_id) REFERENCES worker_rep_agreement (agreement_id),
    CONSTRAINT ck_flex_work_assign_system CHECK (work_system IN
        ('FLEXIBLE_SHORT', 'FLEXIBLE_WRITTEN', 'FLEXIBLE_LONG', 'SELECTIVE', 'DISCRETIONARY')),
    CONSTRAINT ck_flex_work_assign_period CHECK (period_end >= period_start),
    CONSTRAINT ck_flex_work_assign_date_only
        CHECK (period_start = TRUNC(period_start) AND period_end = TRUNC(period_end)),
    -- 근로기준법 제51조 제2항·제51조의2·제52조·제58조 제3항: 서면합의 필수
    CONSTRAINT ck_flex_work_assign_agreement
        CHECK (work_system = 'FLEXIBLE_SHORT' OR agreement_id IS NOT NULL),
    CONSTRAINT ck_flex_work_assign_core CHECK (
        (core_start_min IS NULL AND core_end_min IS NULL)
        OR (work_system = 'SELECTIVE' AND core_start_min BETWEEN 0 AND 1439
            AND core_end_min BETWEEN 1 AND 1440 AND core_end_min > core_start_min)),
    CONSTRAINT ck_flex_work_assign_job CHECK (
        work_system NOT IN ('SELECTIVE', 'DISCRETIONARY') OR job_code IS NOT NULL),
    CONSTRAINT ck_flex_work_assign_deemed CHECK (
        (work_system = 'DISCRETIONARY' AND deemed_minutes BETWEEN 1 AND 1440)
        OR (work_system <> 'DISCRETIONARY' AND deemed_minutes IS NULL))
);

CREATE INDEX ix_flex_work_assign_emp ON flex_work_assign (emp_id, period_start);
CREATE INDEX ix_flex_work_assign_agreement ON flex_work_assign (agreement_id);

CREATE TABLE flex_work_plan (
    flex_id      NUMBER(12)   NOT NULL,
    work_date    DATE         NOT NULL,
    plan_start   TIMESTAMP(0),
    plan_end     TIMESTAMP(0),
    plan_minutes NUMBER(5)    DEFAULT 0 NOT NULL,
    updated_by   VARCHAR2(50 CHAR) NOT NULL,
    updated_at   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_flex_work_plan PRIMARY KEY (flex_id, work_date),
    CONSTRAINT fk_flex_work_plan_assign FOREIGN KEY (flex_id) REFERENCES flex_work_assign (flex_id),
    CONSTRAINT ck_flex_work_plan_date_only CHECK (work_date = TRUNC(work_date)),
    CONSTRAINT ck_flex_work_plan_minutes CHECK (plan_minutes BETWEEN 0 AND 1440),
    CONSTRAINT ck_flex_work_plan_times CHECK (
        (plan_start IS NULL AND plan_end IS NULL AND plan_minutes = 0)
        OR (plan_start IS NOT NULL AND plan_end IS NOT NULL AND plan_end > plan_start))
);
