-- 근로자대표 서면합의서와 첨부파일 (#27). 설계: docs/labor-agreement-design.md
--
-- 규칙
--   - agreement_type: 서면합의가 전제인 제도. 값과 근거 조문은 com.glassehr.attendance.AgreementType 과 같다.
--   - 유효기간은 [valid_from, valid_until] 양 끝 포함(합의서에 적힌 "~까지" 그대로). valid_until NULL = 기간 정함 없음.
--   - 대상 범위: scope_type ALL(회사 전체) 또는 SITE(사업장 한 곳, scope_site_code). target_desc 는 합의서에 적힌
--     대상 근로자 범위(업무·직군 등)를 그대로 옮긴 글이다.
--   - 근로자대표(근로기준법 제24조 제3항): MAJORITY_UNION(근로자 과반수로 조직된 노동조합) 이면 rep_union_name,
--     MAJORITY_PERSON(근로자 과반수를 대표하는 자) 이면 rep_emp_id(사원 참조). 개인정보 최소 수집을 위해 사람 이름을
--     따로 적지 않고 사원 ID 로만 참조한다.
--   - 첨부파일은 DB BLOB 으로 둔다(별도 파일 저장소 없음). 확인용 SHA-256 을 함께 저장한다.
--   - 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.attendance.LaborAgreement, LaborAgreementFile (ddl-auto: validate)

CREATE TABLE labor_agreement (
    agreement_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    agreement_type   VARCHAR2(30 CHAR)   NOT NULL,
    title            VARCHAR2(200 CHAR)  NOT NULL,
    signed_date      DATE                NOT NULL,
    valid_from       DATE                NOT NULL,
    valid_until      DATE,
    scope_type       VARCHAR2(10 CHAR)   NOT NULL,
    scope_site_code  VARCHAR2(3 CHAR),
    target_desc      VARCHAR2(1000 CHAR) NOT NULL,
    rep_type         VARCHAR2(20 CHAR)   NOT NULL,
    rep_union_name   VARCHAR2(200 CHAR),
    rep_emp_id       NUMBER(10),
    note             VARCHAR2(1000 CHAR),
    created_by       VARCHAR2(50 CHAR)   NOT NULL,
    created_at       TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by       VARCHAR2(50 CHAR)   NOT NULL,
    updated_at       TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_labor_agreement PRIMARY KEY (agreement_id),
    CONSTRAINT fk_labor_agreement_site
        FOREIGN KEY (scope_site_code) REFERENCES biz_site (site_code),
    CONSTRAINT fk_labor_agreement_rep_emp
        FOREIGN KEY (rep_emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_labor_agreement_type
        CHECK (agreement_type IN ('FLEXIBLE_WRITTEN', 'FLEXIBLE_LONG', 'SELECTIVE', 'HOLIDAY_SUBSTITUTE',
                                  'COMPENSATORY_LEAVE', 'DISCRETIONARY', 'ANNUAL_LEAVE_SUBSTITUTE')),
    CONSTRAINT ck_labor_agreement_title
        CHECK (TRIM(title) IS NOT NULL),
    CONSTRAINT ck_labor_agreement_target
        CHECK (TRIM(target_desc) IS NOT NULL),
    CONSTRAINT ck_labor_agreement_period
        CHECK (valid_until IS NULL OR valid_until >= valid_from),
    CONSTRAINT ck_labor_agreement_date_only
        CHECK (signed_date = TRUNC(signed_date) AND valid_from = TRUNC(valid_from)
           AND (valid_until IS NULL OR valid_until = TRUNC(valid_until))),
    CONSTRAINT ck_labor_agreement_scope
        CHECK ((scope_type = 'ALL' AND scope_site_code IS NULL)
            OR (scope_type = 'SITE' AND scope_site_code IS NOT NULL)),
    CONSTRAINT ck_labor_agreement_rep
        CHECK ((rep_type = 'MAJORITY_UNION' AND TRIM(rep_union_name) IS NOT NULL AND rep_emp_id IS NULL)
            OR (rep_type = 'MAJORITY_PERSON' AND rep_emp_id IS NOT NULL AND rep_union_name IS NULL))
);

CREATE INDEX ix_labor_agreement_type ON labor_agreement (agreement_type, valid_from);
CREATE INDEX ix_labor_agreement_until ON labor_agreement (valid_until);
CREATE INDEX ix_labor_agreement_rep_emp ON labor_agreement (rep_emp_id);

CREATE TABLE labor_agreement_file (
    file_id       NUMBER(12) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    agreement_id  NUMBER(10)          NOT NULL,
    file_name     VARCHAR2(255 CHAR)  NOT NULL,
    content_type  VARCHAR2(100 CHAR)  NOT NULL,
    file_size     NUMBER(12)          NOT NULL,
    sha256        VARCHAR2(64 CHAR)   NOT NULL,
    content       BLOB                NOT NULL,
    uploaded_by   VARCHAR2(50 CHAR)   NOT NULL,
    uploaded_at   TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_labor_agreement_file PRIMARY KEY (file_id),
    CONSTRAINT fk_labor_agreement_file_agr
        FOREIGN KEY (agreement_id) REFERENCES labor_agreement (agreement_id),
    CONSTRAINT ck_labor_agreement_file_name
        CHECK (TRIM(file_name) IS NOT NULL),
    CONSTRAINT ck_labor_agreement_file_size
        CHECK (file_size > 0),
    CONSTRAINT ck_labor_agreement_file_sha
        CHECK (REGEXP_LIKE(sha256, '^[0-9a-f]+$', 'c') AND LENGTH(sha256) = 64)
);

CREATE INDEX ix_labor_agreement_file_agr ON labor_agreement_file (agreement_id);
