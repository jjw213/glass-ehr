-- 근무 정책(기록·인정 규칙) (#159). 설계: docs/saas-design.md 5장, docs/work-hours-design.md
--
-- 이 마이그레이션이 하는 일
--   1. work_policy: 법인별 근무 정책. pattern_id 가 NULL 이면 법인 기본 정책, 값이 있으면 그 근무유형의 재정의.
--      사용 중(use_yn='Y')인 정책은 (법인, 근무유형)마다 하나 — 함수 기반 UNIQUE 인덱스(숨긴 정책은 색인하지 않는다).
--      쓰인 정책은 지우지 않고 숨긴다(use_yn='N').
--   2. 연장·야간·휴일 허용 방식(UNLIMITED 한도 없이 / DENY 허용 안 함 / LIMIT 일·주·월 한도),
--      법정 근로시간 내 연장 구분, 인정 단위·최소 인정·단위 미달 올림/내림, 정시 출퇴근 인정 범위,
--      이른 출근 기록 허용, 퇴근 기록 누락 처리, 실시간 기록 반영 여부.
-- 법정 수치는 이 테이블에 없다. 법정 한도(주 연장 한도·휴게) 검사는 저장할 때 legal_rate 로 한다(WorkPolicyRules).
-- JPA 엔티티: com.glassehr.attendance.WorkPolicy (ddl-auto: validate)

CREATE TABLE work_policy (
    policy_id              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    enter_cd               VARCHAR2(10 CHAR) NOT NULL,
    pattern_id             NUMBER(10),
    policy_name            VARCHAR2(100 CHAR) NOT NULL,
    ot_mode                VARCHAR2(10 CHAR) DEFAULT 'UNLIMITED' NOT NULL,
    ot_day_limit_min       NUMBER(5),
    ot_week_limit_min      NUMBER(5),
    ot_month_limit_min     NUMBER(5),
    night_mode             VARCHAR2(10 CHAR) DEFAULT 'UNLIMITED' NOT NULL,
    night_day_limit_min    NUMBER(5),
    night_week_limit_min   NUMBER(5),
    night_month_limit_min  NUMBER(5),
    hol_mode               VARCHAR2(10 CHAR) DEFAULT 'UNLIMITED' NOT NULL,
    hol_day_limit_min      NUMBER(5),
    hol_week_limit_min     NUMBER(5),
    hol_month_limit_min    NUMBER(5),
    extra_separate_yn      VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    unit_minutes           NUMBER(3) DEFAULT 1 NOT NULL,
    min_recognize_minutes  NUMBER(3) DEFAULT 0 NOT NULL,
    rounding_mode          VARCHAR2(4 CHAR) DEFAULT 'UP' NOT NULL,
    on_time_in_grace_min   NUMBER(3) DEFAULT 0 NOT NULL,
    on_time_out_grace_min  NUMBER(3) DEFAULT 0 NOT NULL,
    early_in_yn            VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    missing_out_mode       VARCHAR2(20 CHAR) DEFAULT 'IN_ONLY' NOT NULL,
    realtime_yn            VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    use_yn                 VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_by             VARCHAR2(50 CHAR) NOT NULL,
    created_at             TIMESTAMP(6) NOT NULL,
    updated_by             VARCHAR2(50 CHAR) NOT NULL,
    updated_at             TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_work_policy PRIMARY KEY (enter_cd, policy_id),
    CONSTRAINT fk_work_policy_enter FOREIGN KEY (enter_cd) REFERENCES enter_company (enter_cd),
    CONSTRAINT fk_work_policy_pattern FOREIGN KEY (enter_cd, pattern_id) REFERENCES work_pattern (enter_cd, pattern_id),
    CONSTRAINT ck_work_policy_enter CHECK (REGEXP_LIKE(enter_cd, '^[A-Z0-9]+$', 'c') AND LENGTH(enter_cd) >= 2),
    CONSTRAINT ck_work_policy_name CHECK (LENGTH(TRIM(policy_name)) > 0),
    CONSTRAINT ck_work_policy_ot CHECK (ot_mode IN ('UNLIMITED', 'DENY', 'LIMIT')),
    CONSTRAINT ck_work_policy_night CHECK (night_mode IN ('UNLIMITED', 'DENY', 'LIMIT')),
    CONSTRAINT ck_work_policy_hol CHECK (hol_mode IN ('UNLIMITED', 'DENY', 'LIMIT')),
    CONSTRAINT ck_work_policy_limits CHECK (
        (ot_mode = 'LIMIT' OR (ot_day_limit_min IS NULL AND ot_week_limit_min IS NULL AND ot_month_limit_min IS NULL))
        AND (night_mode = 'LIMIT' OR (night_day_limit_min IS NULL AND night_week_limit_min IS NULL AND night_month_limit_min IS NULL))
        AND (hol_mode = 'LIMIT' OR (hol_day_limit_min IS NULL AND hol_week_limit_min IS NULL AND hol_month_limit_min IS NULL))),
    CONSTRAINT ck_work_policy_unit CHECK (unit_minutes BETWEEN 1 AND 60 AND min_recognize_minutes BETWEEN 0 AND 240),
    CONSTRAINT ck_work_policy_rounding CHECK (rounding_mode IN ('UP', 'DOWN')),
    CONSTRAINT ck_work_policy_grace CHECK (on_time_in_grace_min BETWEEN 0 AND 60 AND on_time_out_grace_min BETWEEN 0 AND 60),
    CONSTRAINT ck_work_policy_missing CHECK (missing_out_mode IN ('SCHEDULED_END', 'IN_ONLY', 'CONFIRM_NEXT_DAY')),
    CONSTRAINT ck_work_policy_yn CHECK (extra_separate_yn IN ('Y', 'N') AND early_in_yn IN ('Y', 'N')
        AND realtime_yn IN ('Y', 'N') AND use_yn IN ('Y', 'N'))
);

-- 사용 중 정책은 (법인, 근무유형)마다 하나. 기본 정책(pattern_id NULL)은 0 으로 묶는다(IDENTITY 는 1부터).
CREATE UNIQUE INDEX uq_work_policy_target ON work_policy (
    CASE WHEN use_yn = 'Y' THEN enter_cd END,
    CASE WHEN use_yn = 'Y' THEN NVL(pattern_id, 0) END);

CREATE INDEX ix_work_policy_pattern ON work_policy (enter_cd, pattern_id);
