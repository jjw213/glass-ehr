CREATE TABLE family_leave_request (
    req_id              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id              NUMBER(10)          NOT NULL,
    -- PARENTAL_LEAVE(제19조)·CHILDCARE_REDUCED_HOURS(제19조의2)·FAMILY_CARE_LEAVE(제22조의2)
    leave_kind          VARCHAR2(30 CHAR)   NOT NULL,
    -- 자녀 구분(예: 첫째). 실명·주민등록번호를 넣지 않는다. 같은 자녀의 사용 기간을 이 값으로 모은다.
    child_label         VARCHAR2(30 CHAR),
    -- 자녀 생년월일(출산 전이면 비움). 자녀 나이 확인에만 쓴다.
    child_birth_date    DATE,
    -- 가족돌봄휴직 대상 가족 관계(예: 부모)
    family_relation     VARCHAR2(30 CHAR),
    start_date          DATE                NOT NULL,
    end_date            DATE                NOT NULL,
    -- 육아기 근로시간 단축 근무유형(주 소정근로시간은 work_pattern.weekly_contract_minutes)
    work_pattern_id     NUMBER(10),
    -- 제19조 제2항 추가 육아휴직 요건 충족을 인사 담당자가 확인했는지
    extension_yn        VARCHAR2(1 CHAR)    DEFAULT 'N' NOT NULL,
    reason              VARCHAR2(500 CHAR)  NOT NULL,
    status              VARCHAR2(20 CHAR)   NOT NULL,
    -- 신청 당시 자격 확인 경고(줄바꿈 구분). 자격 판단은 사람이 한다.
    warnings            VARCHAR2(2000 CHAR),
    requested_by        VARCHAR2(50 CHAR)   NOT NULL,
    requested_at        TIMESTAMP(6)        NOT NULL,
    decided_by          VARCHAR2(50 CHAR),
    decided_at          TIMESTAMP(6),
    decision_note       VARCHAR2(500 CHAR),
    leave_appt_id       NUMBER(10),
    return_appt_id      NUMBER(10),
    reduced_assign_id   NUMBER(10),
    restore_assign_id   NUMBER(10),

    CONSTRAINT pk_family_leave_request PRIMARY KEY (req_id),
    CONSTRAINT fk_family_leave_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT fk_family_leave_pattern FOREIGN KEY (work_pattern_id) REFERENCES work_pattern (pattern_id),
    CONSTRAINT fk_family_leave_leave_appt FOREIGN KEY (leave_appt_id) REFERENCES hr_appointment (appt_id),
    CONSTRAINT fk_family_leave_return_appt FOREIGN KEY (return_appt_id) REFERENCES hr_appointment (appt_id),
    CONSTRAINT fk_family_leave_reduced FOREIGN KEY (reduced_assign_id) REFERENCES emp_work_pattern (assign_id),
    CONSTRAINT fk_family_leave_restore FOREIGN KEY (restore_assign_id) REFERENCES emp_work_pattern (assign_id),
    CONSTRAINT ck_family_leave_kind
        CHECK (leave_kind IN ('PARENTAL_LEAVE', 'CHILDCARE_REDUCED_HOURS', 'FAMILY_CARE_LEAVE')),
    CONSTRAINT ck_family_leave_status CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_family_leave_period CHECK (end_date >= start_date),
    CONSTRAINT ck_family_leave_yn CHECK (extension_yn IN ('Y', 'N')),
    CONSTRAINT ck_family_leave_reason CHECK (TRIM(reason) IS NOT NULL),
    CONSTRAINT ck_family_leave_child
        CHECK (leave_kind = 'FAMILY_CARE_LEAVE' OR TRIM(child_label) IS NOT NULL),
    CONSTRAINT ck_family_leave_family
        CHECK (leave_kind <> 'FAMILY_CARE_LEAVE'
            OR (TRIM(family_relation) IS NOT NULL AND child_label IS NULL AND child_birth_date IS NULL)),
    CONSTRAINT ck_family_leave_pattern
        CHECK ((leave_kind = 'CHILDCARE_REDUCED_HOURS' AND work_pattern_id IS NOT NULL)
            OR (leave_kind <> 'CHILDCARE_REDUCED_HOURS' AND work_pattern_id IS NULL)),
    CONSTRAINT ck_family_leave_extension CHECK (extension_yn = 'N' OR leave_kind = 'PARENTAL_LEAVE'),
    CONSTRAINT ck_family_leave_decided
        CHECK (status = 'REQUESTED' OR (decided_by IS NOT NULL AND decided_at IS NOT NULL)),
    CONSTRAINT ck_family_leave_approved
        CHECK (status <> 'APPROVED'
            OR (leave_kind = 'CHILDCARE_REDUCED_HOURS' AND reduced_assign_id IS NOT NULL AND restore_assign_id IS NOT NULL)
            OR (leave_kind <> 'CHILDCARE_REDUCED_HOURS' AND leave_appt_id IS NOT NULL AND return_appt_id IS NOT NULL))
);

CREATE INDEX ix_family_leave_emp ON family_leave_request (emp_id, leave_kind, start_date);
