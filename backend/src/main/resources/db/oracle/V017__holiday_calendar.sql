-- 휴일 달력과 근로자대표 서면합의 (#26). 설계: docs/holiday-calendar-design.md
--
-- 규칙
--   - holiday_kind
--       PUBLIC      법정공휴일(관공서의 공휴일에 관한 규정 제2조). 근로기준법 제55조 제2항·시행령 제30조 제2항 유급휴일.
--       SUBSTITUTE  대체공휴일(관공서의 공휴일에 관한 규정 제3조). 위와 같은 유급휴일.
--       COMPANY     회사휴일(창립기념일 등, 취업규칙·단체협약). 유급 여부는 회사가 정한다(paid_yn).
--       REPLACEMENT 대체된 휴일. 근로기준법 제55조 제2항 단서의 휴일 대체로 공휴일 대신 휴일이 된 근로일.
--                   원래 공휴일(replaces_holiday_id)은 근로일이 된다. 근로자대표 서면합의(agreement_id)가 반드시 있어야 한다.
--   - PUBLIC·SUBSTITUTE 행은 에이전트가 만들지 않는다. 사람이 넣은 CSV(출처·검증일 포함)를 불러와서만 만든다(source_ref 필수).
--   - 날짜는 Asia/Seoul 기준 날짜만(시각 없음). 정규식에 중괄호를 쓰지 않는다(V006 참고).
-- JPA 엔티티: com.glassehr.attendance.Holiday, WorkerRepAgreement (ddl-auto: validate)

CREATE TABLE worker_rep_agreement (
    agreement_id   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    agreement_kind VARCHAR2(30 CHAR)  NOT NULL,
    title          VARCHAR2(200 CHAR) NOT NULL,
    rep_type       VARCHAR2(20 CHAR)  NOT NULL,
    signed_date    DATE               NOT NULL,
    effective_from DATE               NOT NULL,
    effective_to   DATE,
    document_ref   VARCHAR2(500 CHAR) NOT NULL,
    note           VARCHAR2(500 CHAR),
    created_by     VARCHAR2(50 CHAR)  NOT NULL,
    created_at     TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_worker_rep_agreement PRIMARY KEY (agreement_id),
    CONSTRAINT ck_wra_kind CHECK (agreement_kind IN ('HOLIDAY_SUBSTITUTION')),
    CONSTRAINT ck_wra_rep_type CHECK (rep_type IN ('MAJORITY_UNION', 'MAJORITY_REP')),
    CONSTRAINT ck_wra_title CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT ck_wra_document CHECK (LENGTH(TRIM(document_ref)) > 0),
    CONSTRAINT ck_wra_period CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT ck_wra_date_only
        CHECK (signed_date = TRUNC(signed_date) AND effective_from = TRUNC(effective_from)
            AND (effective_to IS NULL OR effective_to = TRUNC(effective_to)))
);

CREATE TABLE holiday (
    holiday_id          NUMBER(12) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    holiday_date        DATE               NOT NULL,
    holiday_name        VARCHAR2(100 CHAR) NOT NULL,
    holiday_kind        VARCHAR2(20 CHAR)  NOT NULL,
    paid_yn             VARCHAR2(1 CHAR)   DEFAULT 'Y' NOT NULL,
    replaces_holiday_id NUMBER(12),
    agreement_id        NUMBER(10),
    source_ref          VARCHAR2(500 CHAR),
    verified_date       DATE,
    note                VARCHAR2(500 CHAR),
    created_by          VARCHAR2(50 CHAR)  NOT NULL,
    created_at          TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_holiday PRIMARY KEY (holiday_id),
    CONSTRAINT uq_holiday_date_name UNIQUE (holiday_date, holiday_name),
    CONSTRAINT uq_holiday_replaces UNIQUE (replaces_holiday_id),
    CONSTRAINT fk_holiday_replaces
        FOREIGN KEY (replaces_holiday_id) REFERENCES holiday (holiday_id),
    CONSTRAINT fk_holiday_agreement
        FOREIGN KEY (agreement_id) REFERENCES worker_rep_agreement (agreement_id),
    CONSTRAINT ck_holiday_kind
        CHECK (holiday_kind IN ('PUBLIC', 'SUBSTITUTE', 'COMPANY', 'REPLACEMENT')),
    CONSTRAINT ck_holiday_name CHECK (LENGTH(TRIM(holiday_name)) > 0),
    CONSTRAINT ck_holiday_paid CHECK (paid_yn IN ('Y', 'N')),
    -- 공휴일·대체공휴일·대체된 휴일은 유급(근로기준법 제55조 제2항). 무급은 회사휴일만 가능.
    CONSTRAINT ck_holiday_paid_legal CHECK (holiday_kind = 'COMPANY' OR paid_yn = 'Y'),
    -- 휴일 대체는 원래 공휴일과 근로자대표 서면합의가 모두 있어야 한다(제55조 제2항 단서). 다른 종류는 둘 다 없다.
    CONSTRAINT ck_holiday_replacement
        CHECK ((holiday_kind = 'REPLACEMENT' AND replaces_holiday_id IS NOT NULL AND agreement_id IS NOT NULL)
            OR (holiday_kind <> 'REPLACEMENT' AND replaces_holiday_id IS NULL AND agreement_id IS NULL)),
    -- 공휴일 데이터는 사람이 넣은 출처가 있는 자료로만 만든다.
    CONSTRAINT ck_holiday_public_source
        CHECK (holiday_kind NOT IN ('PUBLIC', 'SUBSTITUTE') OR (source_ref IS NOT NULL AND verified_date IS NOT NULL)),
    CONSTRAINT ck_holiday_date_only
        CHECK (holiday_date = TRUNC(holiday_date) AND (verified_date IS NULL OR verified_date = TRUNC(verified_date)))
);

CREATE INDEX ix_holiday_agreement ON holiday (agreement_id);
