-- 근로계약 이력 (#17). 설계: docs/employment-contract-design.md
--
-- 근거 (2026-11-12 law.go.kr 자동 조회가 되지 않아 원문 미확인. 사람이 원문으로 다시 확인해야 한다)
--   - 근로기준법 제17조 제1항: 임금, 소정근로시간, 제55조 휴일, 제60조 연차 유급휴가, 그 밖에 대통령령으로 정하는 근로조건을 명시
--   - 근로기준법 시행령 제8조 제1호: 취업의 장소와 종사하여야 할 업무에 관한 사항
--   - 근로기준법 제17조 제2항: 임금의 구성항목·계산방법·지급방법과 제1항 제2호~제4호 사항을 적은 서면 교부
--   - 기간제법 제17조: 기간제·단시간근로자는 계약기간, 근로시간·휴게, 임금 구성항목·계산방법·지불방법, 휴일·휴가,
--     취업 장소·업무, (단시간) 근로일 및 근로일별 근로시간을 서면으로 명시
--   - 기간제법 제4조: 기간제근로자 사용기간 상한은 legal_rate FIXED_TERM_MAX_USE_YEARS(V011)에서 읽는다
--   - 근로기준법 제42조: 계약 서류 보존. 계약 행은 지우지 않는다(삭제 API 없음)
--
-- 명시사항 컬럼은 NULL 을 허용한다. 누락은 저장을 막지 않고 경고로 알린다(ContractTermsChecker). 이슈 #17 "누락 시 저장 시 경고".
-- 정규식·중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.contract.EmploymentContract (ddl-auto: validate)

CREATE TABLE employment_contract (
    contract_id             NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id                  NUMBER(10)          NOT NULL,
    -- 고용형태 공통코드(EMPLOYMENT_TYPE): REGULAR·FIXED_TERM·PART_TIME
    contract_type_code      VARCHAR2(30 CHAR)   NOT NULL,
    -- 체결일
    contract_date           DATE                NOT NULL,
    -- 계약기간(기간제법 제17조 제1호). 종료일 NULL = 기간의 정함 없음
    start_date              DATE                NOT NULL,
    end_date                DATE,
    -- 임금(제17조 제1항 제1호). 원 단위 정수
    wage_amount             NUMBER(15),
    wage_unit_code          VARCHAR2(10 CHAR),
    -- 임금의 구성항목·계산방법·지급방법(제17조 제2항, 기간제법 제17조 제3호)
    wage_components         VARCHAR2(1000 CHAR),
    wage_calc_method        VARCHAR2(1000 CHAR),
    wage_payment_method     VARCHAR2(1000 CHAR),
    -- 소정근로시간(제17조 제1항 제2호). 1주 분 단위
    weekly_contract_minutes NUMBER(5),
    -- 근로시간·휴게(기간제법 제17조 제2호): 시업·종업 시각, 휴게시간
    work_hours_text         VARCHAR2(1000 CHAR),
    -- 근로일 및 근로일별 근로시간(기간제법 제17조 제6호, 단시간근로자)
    work_days_text          VARCHAR2(1000 CHAR),
    -- 휴일(제17조 제1항 제3호, 제55조)
    holiday_text            VARCHAR2(1000 CHAR),
    -- 연차 유급휴가 등 휴가(제17조 제1항 제4호, 제60조)
    leave_text              VARCHAR2(1000 CHAR),
    -- 취업의 장소와 종사하여야 할 업무(시행령 제8조 제1호)
    work_place              VARCHAR2(300 CHAR),
    job_duty                VARCHAR2(500 CHAR),
    -- 그 밖의 근로조건(시행령 제8조 제2호·제3호: 취업규칙·기숙사 규칙 사항 등)
    other_terms             VARCHAR2(2000 CHAR),
    -- 서면 교부일(제17조 제2항, 기간제법 제17조). NULL = 미교부
    written_delivered_date  DATE,

    created_at              TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_employment_contract PRIMARY KEY (contract_id),
    CONSTRAINT fk_employment_contract_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_emp_contract_period CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_emp_contract_fixed_end CHECK (contract_type_code <> 'FIXED_TERM' OR end_date IS NOT NULL),
    CONSTRAINT ck_emp_contract_wage CHECK (wage_amount IS NULL OR wage_amount >= 0),
    CONSTRAINT ck_emp_contract_wage_unit
        CHECK (wage_unit_code IS NULL OR wage_unit_code IN ('HOURLY', 'DAILY', 'WEEKLY', 'MONTHLY', 'ANNUAL')),
    CONSTRAINT ck_emp_contract_minutes CHECK (weekly_contract_minutes IS NULL OR weekly_contract_minutes > 0),
    CONSTRAINT ck_emp_contract_delivered
        CHECK (written_delivered_date IS NULL OR written_delivered_date >= contract_date),
    CONSTRAINT ck_emp_contract_date_only
        CHECK (contract_date = TRUNC(contract_date) AND start_date = TRUNC(start_date)
            AND (end_date IS NULL OR end_date = TRUNC(end_date))
            AND (written_delivered_date IS NULL OR written_delivered_date = TRUNC(written_delivered_date)))
);

CREATE INDEX ix_emp_contract_emp ON employment_contract (emp_id, start_date);
CREATE INDEX ix_emp_contract_end ON employment_contract (end_date);
CREATE INDEX ix_emp_contract_undelivered ON employment_contract (written_delivered_date);
