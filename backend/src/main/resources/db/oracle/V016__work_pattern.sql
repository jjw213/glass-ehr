-- 근무유형과 사원별 근무유형 배정 이력 (#25). 설계: docs/work-pattern-design.md
--
-- 규칙
--   - 시각은 자정부터의 분(0~1439) 정수. 종업 시각이 시업 시각 이하이면 다음 날 종업(야간조)으로 본다.
--   - 휴게는 한 구간(break_start_min 부터 break_minutes 분). 휴게가 없으면 break_start_min NULL, break_minutes 0.
--   - day_types: 월~일 7글자. W = 근무일(소정근로일), O = 휴무일(무급), H = 주휴일(근로기준법 제55조 제1항 유급휴일).
--   - 1일 소정근로시간 = (종업 - 시업) - 휴게. 1주 = 1일 x 근무일 수. 이 값은 서비스가 계산해 저장한다.
--   - 법정 한도(제50조)·휴게(제54조)·주휴일(제55조) 검사는 서비스가 legal_rate 적용값으로 한다(값을 DB에 쓰지 않음).
--   - 배정에서 이미 쓰인 근무유형은 시각·휴게·요일 구분을 바꿀 수 없다(과거 근태 재계산이 달라지지 않게). 새 유형을 만든다.
--   - 배정 이력은 유효기간 방식 [valid_from, valid_to), valid_to NULL = 현재. 추가로만 쌓는다(#8 과 같은 방식).
--   - 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.attendance.WorkPattern, EmpWorkPattern (ddl-auto: validate)

CREATE TABLE work_pattern (
    pattern_id              NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    pattern_code            VARCHAR2(20 CHAR)  NOT NULL,
    pattern_name            VARCHAR2(100 CHAR) NOT NULL,
    work_start_min          NUMBER(4)          NOT NULL,
    work_end_min            NUMBER(4)          NOT NULL,
    break_start_min         NUMBER(4),
    break_minutes           NUMBER(4)          DEFAULT 0 NOT NULL,
    day_types               VARCHAR2(7 CHAR)   NOT NULL,
    daily_contract_minutes  NUMBER(5)          NOT NULL,
    weekly_contract_minutes NUMBER(5)          NOT NULL,
    use_yn                  VARCHAR2(1 CHAR)   DEFAULT 'Y' NOT NULL,
    note                    VARCHAR2(500 CHAR),
    created_at              TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_work_pattern PRIMARY KEY (pattern_id),
    CONSTRAINT uq_work_pattern_code UNIQUE (pattern_code),
    CONSTRAINT ck_work_pattern_code
        CHECK (REGEXP_LIKE(pattern_code, '^[A-Z0-9][A-Z0-9_]*$', 'c')),
    CONSTRAINT ck_work_pattern_name
        CHECK (LENGTH(TRIM(pattern_name)) > 0),
    CONSTRAINT ck_work_pattern_start
        CHECK (work_start_min BETWEEN 0 AND 1439),
    CONSTRAINT ck_work_pattern_end
        CHECK (work_end_min BETWEEN 0 AND 1439),
    CONSTRAINT ck_work_pattern_break_start
        CHECK (break_start_min IS NULL OR break_start_min BETWEEN 0 AND 1439),
    CONSTRAINT ck_work_pattern_break
        CHECK ((break_minutes = 0 AND break_start_min IS NULL)
            OR (break_minutes > 0 AND break_start_min IS NOT NULL)),
    CONSTRAINT ck_work_pattern_days
        CHECK (LENGTH(day_types) = 7 AND REGEXP_LIKE(day_types, '^[WOH]+$', 'c')),
    CONSTRAINT ck_work_pattern_has_holiday
        CHECK (INSTR(day_types, 'H') > 0),
    CONSTRAINT ck_work_pattern_has_workday
        CHECK (INSTR(day_types, 'W') > 0),
    CONSTRAINT ck_work_pattern_minutes
        CHECK (daily_contract_minutes > 0 AND weekly_contract_minutes > 0),
    CONSTRAINT ck_work_pattern_use
        CHECK (use_yn IN ('Y', 'N'))
);

CREATE TABLE emp_work_pattern (
    assign_id     NUMBER(12) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id        NUMBER(10)         NOT NULL,
    pattern_id    NUMBER(10)         NOT NULL,
    valid_from    DATE               NOT NULL,
    valid_to      DATE,
    assign_reason VARCHAR2(500 CHAR),
    created_by    VARCHAR2(50 CHAR)  NOT NULL,
    created_at    TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_emp_work_pattern PRIMARY KEY (assign_id),
    CONSTRAINT fk_emp_work_pattern_emp
        FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT fk_emp_work_pattern_pattern
        FOREIGN KEY (pattern_id) REFERENCES work_pattern (pattern_id),
    CONSTRAINT uq_emp_work_pattern_start UNIQUE (emp_id, valid_from),
    CONSTRAINT ck_emp_work_pattern_period
        CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_emp_work_pattern_date_only
        CHECK (valid_from = TRUNC(valid_from) AND (valid_to IS NULL OR valid_to = TRUNC(valid_to)))
);

CREATE INDEX ix_emp_work_pattern_pattern ON emp_work_pattern (pattern_id);
