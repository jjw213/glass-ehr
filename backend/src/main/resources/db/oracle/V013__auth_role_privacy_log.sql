-- 역할·권한과 개인정보 조회 로그 (#19). 설계: docs/auth-design.md
--
-- 근거
--   - 개인정보 보호법 제29조(안전조치의무)와 개인정보의 안전성 확보조치 기준(고시)의 접근 권한 관리·접속기록 보관.
--     고시의 세부 조항 번호와 접속기록 보관 기간은 원문을 확인하지 못했다(docs/auth-design.md 6장 미결).
--     그래서 이 마이그레이션은 보관 기간을 정하지 않고, 로그를 지우는 기능도 두지 않는다.
--
-- 규칙
--   - 권한 검사는 API 단에서 한다(com.glassehr.auth.AuthInterceptor). 화면 메뉴 숨김은 보조 수단이다.
--   - 역할은 요청 헤더가 아니라 이 테이블(app_user_role)에서 읽는다.
--   - 부서장(DEPT_HEAD)은 직접 부여하지 않는다. 조직 이력(org_dept_hist.head_emp_id)에 기준일 부서장으로
--     지정된 사원에게 자동으로 붙는다. 데이터 범위는 그 부서와 모든 하위부서다.
--   - 일반 사원(EMPLOYEE)은 로그인한 모든 사용자에게 자동으로 붙는다(본인 정보만).
--   - 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.auth.* (ddl-auto: validate)

CREATE TABLE app_role (
    role_code   VARCHAR2(20 CHAR)  NOT NULL,
    role_name   VARCHAR2(50 CHAR)  NOT NULL,
    sort_order  NUMBER(5)          NOT NULL,

    CONSTRAINT pk_app_role PRIMARY KEY (role_code),
    CONSTRAINT ck_app_role_code CHECK (REGEXP_LIKE(role_code, '^[A-Z][A-Z_]*$', 'c'))
);

CREATE TABLE app_permission (
    perm_code   VARCHAR2(30 CHAR)  NOT NULL,
    perm_name   VARCHAR2(100 CHAR) NOT NULL,

    CONSTRAINT pk_app_permission PRIMARY KEY (perm_code),
    CONSTRAINT ck_app_permission_code CHECK (REGEXP_LIKE(perm_code, '^[A-Z][A-Z_]*$', 'c'))
);

CREATE TABLE app_role_permission (
    role_code   VARCHAR2(20 CHAR)  NOT NULL,
    perm_code   VARCHAR2(30 CHAR)  NOT NULL,

    CONSTRAINT pk_app_role_permission PRIMARY KEY (role_code, perm_code),
    CONSTRAINT fk_app_role_perm_role FOREIGN KEY (role_code) REFERENCES app_role (role_code),
    CONSTRAINT fk_app_role_perm_perm FOREIGN KEY (perm_code) REFERENCES app_permission (perm_code)
);

-- 로그인 사용자. 비밀번호·인증 수단은 인증 이슈에서 붙인다(지금은 X-Actor-Id 로 사용자를 찾음, docs/auth-design.md 2장).
-- emp_id 는 본인 정보·부서장 범위 판단에 쓴다(사원이 아닌 시스템 관리자 계정은 비워 둘 수 있음).
CREATE TABLE app_user (
    login_id    VARCHAR2(50 CHAR)  NOT NULL,
    emp_id      NUMBER(10),
    active_yn   CHAR(1)            DEFAULT 'Y' NOT NULL,
    created_at  TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_app_user PRIMARY KEY (login_id),
    CONSTRAINT uq_app_user_emp UNIQUE (emp_id),
    CONSTRAINT fk_app_user_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_app_user_login_id CHECK (LENGTH(TRIM(login_id)) > 0),
    CONSTRAINT ck_app_user_active_yn CHECK (active_yn IN ('Y', 'N'))
);

-- 사용자별 부여 역할. 부서장·일반 사원은 자동으로 붙으므로 여기 넣지 않는다.
CREATE TABLE app_user_role (
    login_id    VARCHAR2(50 CHAR)  NOT NULL,
    role_code   VARCHAR2(20 CHAR)  NOT NULL,

    CONSTRAINT pk_app_user_role PRIMARY KEY (login_id, role_code),
    CONSTRAINT fk_app_user_role_user FOREIGN KEY (login_id) REFERENCES app_user (login_id),
    CONSTRAINT fk_app_user_role_role FOREIGN KEY (role_code) REFERENCES app_role (role_code),
    CONSTRAINT ck_app_user_role_assignable CHECK (role_code NOT IN ('DEPT_HEAD', 'EMPLOYEE'))
);

-- 개인정보 조회·다운로드 로그(누가, 언제, 누구의, 무엇을). 추가만 한다(엔티티는 @Immutable, 삭제 API 없음).
-- 주민등록번호 원문 조회는 기존 rrn_access_log(V009)에 남고, 로그 조회 화면이 두 테이블을 함께 보여 준다.
-- 거부·대상 없음도 남긴다. 원문 값은 남기지 않는다.
--   item_code    EMP_PERSONAL(인적사항: 생년월일·주소·이력·메모), EMP_LIST(사원 목록 파일), RRN(주민등록번호)
--   action_code  VIEW(화면 조회), DOWNLOAD(파일 내려받기)
--   target_emp_id 대상 사원. 목록 다운로드는 파일에 들어간 사원마다 한 행. 거부된 다운로드처럼 대상이 없으면 NULL.
--                 존재하지 않는 사원 조회 시도도 남겨야 하므로 FK 를 걸지 않는다.
CREATE TABLE privacy_access_log (
    log_id          NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    accessor_id     VARCHAR2(50 CHAR)   NOT NULL,
    accessor_roles  VARCHAR2(200 CHAR),
    target_emp_id   NUMBER(10),
    item_code       VARCHAR2(20 CHAR)   NOT NULL,
    action_code     VARCHAR2(10 CHAR)   NOT NULL,
    result          VARCHAR2(10 CHAR)   NOT NULL,
    client_ip       VARCHAR2(45 CHAR),
    request_path    VARCHAR2(200 CHAR),
    accessed_at     TIMESTAMP(6)        NOT NULL,

    CONSTRAINT pk_privacy_access_log PRIMARY KEY (log_id),
    CONSTRAINT ck_privacy_log_item CHECK (item_code IN ('EMP_PERSONAL', 'EMP_LIST', 'RRN')),
    CONSTRAINT ck_privacy_log_action CHECK (action_code IN ('VIEW', 'DOWNLOAD')),
    CONSTRAINT ck_privacy_log_result CHECK (result IN ('SUCCESS', 'DENIED', 'NOT_FOUND'))
);

CREATE INDEX ix_privacy_log_at ON privacy_access_log (accessed_at);
CREATE INDEX ix_privacy_log_target ON privacy_access_log (target_emp_id, accessed_at);
CREATE INDEX ix_privacy_log_accessor ON privacy_access_log (accessor_id, accessed_at);
CREATE INDEX ix_rrn_access_log_at ON rrn_access_log (accessed_at);

