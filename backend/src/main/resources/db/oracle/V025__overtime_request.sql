-- 연장·휴일근로 사전 신청 (#30). 설계: docs/overtime-request-design.md
--
-- 규칙
--   - 신청은 공통 결재(V024)로 올린다. approval_doc.request_type = 'OVERTIME', request_ref = overtime_request.request_id.
--   - status 는 결재 결과를 그대로 따른다: IN_PROGRESS 결재 중, APPROVED 승인, REJECTED 반려, WITHDRAWN 회수.
--   - 예정 근로시간(planned_minutes)은 시작~종료에서 휴게를 뺀 분 단위 정수. 서비스가 계산해 넣고 CHECK 로 다시 확인한다.
--   - 승인 시점에 그 주(근로기준법 제2조 제1항 제7호: 휴일 포함 7일)의 연장근로 합계가
--     legal_rate WEEKLY_OVERTIME_LIMIT_HOURS(근로기준법 제53조 제1항)를 넘으면 승인하지 않는다.
--     특별연장근로 인가(special_overtime_auth, 제53조 제4항)는 이 이슈에서 정보 입력·조회만 한다(한도 검사와 연결하지 않음).
--   - 정규식에 중괄호를 쓰지 않는다(V006 참고).
-- JPA 엔티티: com.glassehr.overtime.* (ddl-auto: validate)

-- 특별연장근로 인가 정보(근로기준법 제53조 제4항). 이 이슈에서는 입력·조회만 한다.
--   auth_kind: PRIOR 사전 인가, POST 사후 승인(단서: 사태가 급박해 인가를 받을 시간이 없는 경우)
CREATE TABLE special_overtime_auth (
    auth_id        NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    auth_kind      VARCHAR2(5 CHAR)    NOT NULL,
    auth_no        VARCHAR2(50 CHAR)   NOT NULL,
    labor_office   VARCHAR2(100 CHAR)  NOT NULL,
    authorized_on  DATE                NOT NULL,
    period_from    DATE                NOT NULL,
    period_to      DATE                NOT NULL,
    reason         VARCHAR2(500 CHAR)  NOT NULL,
    worker_consent CHAR(1)             NOT NULL,
    created_by     VARCHAR2(50 CHAR)   NOT NULL,
    created_at     TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_special_overtime_auth PRIMARY KEY (auth_id),
    CONSTRAINT uq_special_overtime_auth_no UNIQUE (auth_no),
    CONSTRAINT ck_sot_auth_kind CHECK (auth_kind IN ('PRIOR', 'POST')),
    CONSTRAINT ck_sot_auth_no CHECK (TRIM(auth_no) IS NOT NULL),
    CONSTRAINT ck_sot_office CHECK (TRIM(labor_office) IS NOT NULL),
    CONSTRAINT ck_sot_reason CHECK (TRIM(reason) IS NOT NULL),
    CONSTRAINT ck_sot_consent CHECK (worker_consent = 'Y'),
    CONSTRAINT ck_sot_dates CHECK (authorized_on = TRUNC(authorized_on) AND period_from = TRUNC(period_from)
        AND period_to = TRUNC(period_to) AND period_to >= period_from)
);

-- 인가 대상 사원
CREATE TABLE special_overtime_auth_emp (
    auth_id  NUMBER(15)  NOT NULL,
    emp_id   NUMBER(10)  NOT NULL,

    CONSTRAINT pk_special_overtime_auth_emp PRIMARY KEY (auth_id, emp_id),
    CONSTRAINT fk_sot_emp_auth FOREIGN KEY (auth_id) REFERENCES special_overtime_auth (auth_id),
    CONSTRAINT fk_sot_emp_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id)
);

-- 연장·휴일근로 신청. work_kind: OVERTIME 연장근로, HOLIDAY 휴일근로
CREATE TABLE overtime_request (
    request_id       NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id           NUMBER(10)          NOT NULL,
    work_kind        VARCHAR2(10 CHAR)   NOT NULL,
    work_date        DATE                NOT NULL,
    start_at         TIMESTAMP(0)        NOT NULL,
    end_at           TIMESTAMP(0)        NOT NULL,
    break_minutes    NUMBER(4)           DEFAULT 0 NOT NULL,
    planned_minutes  NUMBER(5)           NOT NULL,
    reason           VARCHAR2(500 CHAR)  NOT NULL,
    status          VARCHAR2(12 CHAR)   NOT NULL,
    requested_at     TIMESTAMP(6)        NOT NULL,
    decided_at       TIMESTAMP(6),

    CONSTRAINT pk_overtime_request PRIMARY KEY (request_id),
    CONSTRAINT fk_overtime_request_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_overtime_request_kind CHECK (work_kind IN ('OVERTIME', 'HOLIDAY')),
    CONSTRAINT ck_overtime_request_date CHECK (work_date = TRUNC(work_date)),
    CONSTRAINT ck_overtime_request_range CHECK (end_at > start_at AND start_at >= work_date
        AND start_at < work_date + 1),
    CONSTRAINT ck_overtime_request_minutes CHECK (break_minutes >= 0 AND planned_minutes > 0
        AND planned_minutes = ROUND((CAST(end_at AS DATE) - CAST(start_at AS DATE)) * 1440) - break_minutes),
    CONSTRAINT ck_overtime_request_reason CHECK (TRIM(reason) IS NOT NULL),
    CONSTRAINT ck_overtime_request_status CHECK (status IN ('IN_PROGRESS', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_overtime_request_decided CHECK ((status = 'IN_PROGRESS' AND decided_at IS NULL)
        OR (status <> 'IN_PROGRESS' AND decided_at IS NOT NULL))
);

CREATE INDEX ix_overtime_request_emp_date ON overtime_request (emp_id, work_date);
