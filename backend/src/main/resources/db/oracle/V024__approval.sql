-- 공통 결재 (#30). 설계: docs/approval-line-design.md
--
-- 규칙
--   - 결재선 템플릿은 신청 유형별 유효기간 [valid_from, valid_to) 방식. 바꿀 때는 기존 행에 종료일을 넣고 새 행을 추가한다.
--     한 신청 유형에 열린 템플릿(valid_to NULL)은 하나뿐이다(ux_approval_template_open).
--   - 결재 문서는 신청일(Asia/Seoul) 기준으로 결재자를 실제 사원으로 풀어 단계·결재자 후보를 복사(스냅샷)한다.
--     이후 템플릿이 바뀌거나 부서장이 바뀌어도 진행 중 문서의 결재선은 바뀌지 않는다.
--   - 결재자를 찾지 못하면 신청을 받지 않는다. ROLE·POSITION 은 후보 중 아무나 한 명이 결재한다(2026-11-19 사람 답변 1번안).
--   - 결재는 순차. 한 단계라도 반려하면 문서 전체가 반려된다. 회수는 첫 승인 전에만 신청자가 한다.
--   - 처리 이력(approval_action_log)은 추가만 한다(엔티티 @Immutable, 수정·삭제 API 없음).
--   - 정규식에 중괄호를 쓰지 않는다(V006 참고).
-- JPA 엔티티: com.glassehr.approval.* (ddl-auto: validate)

CREATE TABLE approval_template (
    template_id   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_type  VARCHAR2(30 CHAR)  NOT NULL,
    valid_from    DATE               NOT NULL,
    valid_to      DATE,
    created_by    VARCHAR2(50 CHAR)  NOT NULL,
    created_at    TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_approval_template PRIMARY KEY (template_id),
    CONSTRAINT uq_approval_template_from UNIQUE (request_type, valid_from),
    CONSTRAINT ck_approval_template_type CHECK (REGEXP_LIKE(request_type, '^[A-Z][A-Z_]*$', 'c')),
    CONSTRAINT ck_approval_template_dates CHECK (valid_from = TRUNC(valid_from)
        AND (valid_to IS NULL OR (valid_to = TRUNC(valid_to) AND valid_to > valid_from)))
);

CREATE UNIQUE INDEX ux_approval_template_open
    ON approval_template (CASE WHEN valid_to IS NULL THEN request_type END);

CREATE TABLE approval_template_step (
    template_id    NUMBER(10)         NOT NULL,
    step_no        NUMBER(2)          NOT NULL,
    approver_kind  VARCHAR2(20 CHAR)  NOT NULL,
    approver_ref   VARCHAR2(50 CHAR),
    skip_if_self   CHAR(1)            DEFAULT 'N' NOT NULL,

    CONSTRAINT pk_approval_template_step PRIMARY KEY (template_id, step_no),
    CONSTRAINT fk_approval_tstep_template FOREIGN KEY (template_id) REFERENCES approval_template (template_id),
    CONSTRAINT ck_approval_tstep_no CHECK (step_no BETWEEN 1 AND 10),
    CONSTRAINT ck_approval_tstep_kind
        CHECK (approver_kind IN ('DEPT_HEAD', 'UPPER_DEPT_HEAD', 'POSITION', 'ROLE', 'EMPLOYEE')),
    CONSTRAINT ck_approval_tstep_ref
        CHECK ((approver_kind IN ('DEPT_HEAD', 'UPPER_DEPT_HEAD') AND approver_ref IS NULL)
            OR (approver_kind IN ('POSITION', 'ROLE', 'EMPLOYEE') AND TRIM(approver_ref) IS NOT NULL)),
    CONSTRAINT ck_approval_tstep_skip CHECK (skip_if_self IN ('Y', 'N'))
);

-- 결재 문서. request_ref 는 각 모듈의 원본 신청 ID(예: overtime_request.request_id). 모듈 테이블이 여럿이라 FK 를 걸지 않는다.
--   status: IN_PROGRESS 진행 중, APPROVED 승인, REJECTED 반려, WITHDRAWN 회수
CREATE TABLE approval_doc (
    approval_id       NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    request_type      VARCHAR2(30 CHAR)  NOT NULL,
    request_ref       NUMBER(15)         NOT NULL,
    title             VARCHAR2(200 CHAR) NOT NULL,
    requester_emp_id  NUMBER(10)         NOT NULL,
    template_id       NUMBER(10)         NOT NULL,
    status            VARCHAR2(12 CHAR)  NOT NULL,
    current_step_no   NUMBER(2),
    submitted_at      TIMESTAMP(6)       NOT NULL,
    completed_at      TIMESTAMP(6),

    CONSTRAINT pk_approval_doc PRIMARY KEY (approval_id),
    CONSTRAINT uq_approval_doc_ref UNIQUE (request_type, request_ref),
    CONSTRAINT fk_approval_doc_requester FOREIGN KEY (requester_emp_id) REFERENCES employee (emp_id),
    CONSTRAINT fk_approval_doc_template FOREIGN KEY (template_id) REFERENCES approval_template (template_id),
    CONSTRAINT ck_approval_doc_title CHECK (TRIM(title) IS NOT NULL),
    CONSTRAINT ck_approval_doc_status CHECK (status IN ('IN_PROGRESS', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT ck_approval_doc_progress
        CHECK ((status = 'IN_PROGRESS' AND current_step_no IS NOT NULL AND completed_at IS NULL)
            OR (status <> 'IN_PROGRESS' AND current_step_no IS NULL AND completed_at IS NOT NULL))
);

CREATE INDEX ix_approval_doc_requester ON approval_doc (requester_emp_id, submitted_at);

-- 결재 문서 단계(스냅샷). step_status: WAITING 대기, APPROVED 승인, REJECTED 반려, SKIPPED 본인 결재 건너뜀
CREATE TABLE approval_doc_step (
    step_id        NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    approval_id    NUMBER(15)         NOT NULL,
    step_no        NUMBER(2)          NOT NULL,
    approver_kind  VARCHAR2(20 CHAR)  NOT NULL,
    approver_ref   VARCHAR2(50 CHAR),
    step_status    VARCHAR2(10 CHAR)  NOT NULL,
    acted_emp_id   NUMBER(10),
    acted_at       TIMESTAMP(6),
    step_comment   VARCHAR2(500 CHAR),

    CONSTRAINT pk_approval_doc_step PRIMARY KEY (step_id),
    CONSTRAINT uq_approval_doc_step UNIQUE (approval_id, step_no),
    CONSTRAINT fk_approval_dstep_doc FOREIGN KEY (approval_id) REFERENCES approval_doc (approval_id),
    CONSTRAINT fk_approval_dstep_actor FOREIGN KEY (acted_emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_approval_dstep_no CHECK (step_no BETWEEN 1 AND 10),
    CONSTRAINT ck_approval_dstep_status CHECK (step_status IN ('WAITING', 'APPROVED', 'REJECTED', 'SKIPPED')),
    CONSTRAINT ck_approval_dstep_acted
        CHECK ((step_status IN ('APPROVED', 'REJECTED') AND acted_emp_id IS NOT NULL AND acted_at IS NOT NULL)
            OR (step_status IN ('WAITING', 'SKIPPED') AND acted_emp_id IS NULL))
);

-- 단계별 결재자 후보(신청 시점에 확정). 후보 중 한 명이 처리한다. SKIPPED 단계는 후보가 없을 수 있다.
CREATE TABLE approval_doc_step_approver (
    step_id  NUMBER(15)  NOT NULL,
    emp_id   NUMBER(10)  NOT NULL,

    CONSTRAINT pk_approval_dstep_approver PRIMARY KEY (step_id, emp_id),
    CONSTRAINT fk_approval_dsa_step FOREIGN KEY (step_id) REFERENCES approval_doc_step (step_id),
    CONSTRAINT fk_approval_dsa_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id)
);

CREATE INDEX ix_approval_dsa_emp ON approval_doc_step_approver (emp_id);

-- 처리 이력(추가만). action: SUBMIT 제출, SKIP 본인 단계 건너뜀, APPROVE 승인, REJECT 반려, WITHDRAW 회수
CREATE TABLE approval_action_log (
    action_id       NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    approval_id     NUMBER(15)         NOT NULL,
    step_no         NUMBER(2),
    action          VARCHAR2(10 CHAR)  NOT NULL,
    actor_emp_id    NUMBER(10)         NOT NULL,
    acted_at        TIMESTAMP(6)       NOT NULL,
    action_comment  VARCHAR2(500 CHAR),

    CONSTRAINT pk_approval_action_log PRIMARY KEY (action_id),
    CONSTRAINT fk_approval_log_doc FOREIGN KEY (approval_id) REFERENCES approval_doc (approval_id),
    CONSTRAINT fk_approval_log_actor FOREIGN KEY (actor_emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_approval_log_action CHECK (action IN ('SUBMIT', 'SKIP', 'APPROVE', 'REJECT', 'WITHDRAW'))
);

CREATE INDEX ix_approval_log_doc ON approval_action_log (approval_id, action_id);
