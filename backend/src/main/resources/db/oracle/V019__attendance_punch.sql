-- 출퇴근 원시 기록 (#28). 설계: docs/attendance-punch-design.md (#22 결정), 구현 범위는 같은 문서 §8.
--
-- 규칙
--   - 원시 기록은 추가만 한다. 애플리케이션에 수정·삭제 API·메서드가 없다. 정정은 별도 정정 행으로 한다(별도 이슈).
--   - punched_at 은 서버 시각(Asia/Seoul)이다. 단말이 보낸 시각(client_time)은 참고로만 남기고 근태 계산에 쓰지 않는다.
--   - work_date 는 서버 시각의 날짜(Asia/Seoul)다. 야간 근무의 날짜 넘김 귀속은 근무일정·집계 이슈에서 정한다.
--   - punch_check 는 기록 당시 판정(막지 않고 저장, 관리자 확인 대상):
--       NULL            정상
--       DUPLICATE_IN    같은 근무일에 이미 출근 기록이 있는데 다시 출근
--       OUT_WITHOUT_IN  같은 근무일에 출근 기록이 없는데 퇴근
--     퇴근을 여러 번 누르는 것은 정상(마지막 퇴근이 퇴근 시각). 집계 규칙은 첫 출근·마지막 퇴근(§8).
--   - 위치 확인(GPS)·동의 이력 칼럼은 위치 확인 이슈에서 추가한다(§7 미결 사항 확정 후).
--   - 근거: 근로기준법 제48조(임금대장)·시행령 제27조(근로시간수 등 기재사항) — 근로시간 기재의 원자료.
--   - 정규식에 중괄호를 쓰지 않는다(V006 참고).
-- JPA 엔티티: com.glassehr.attendance.AttendancePunch (ddl-auto: validate)

CREATE TABLE attendance_punch (
    punch_id    NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id      NUMBER(10)        NOT NULL,
    punch_type  VARCHAR2(3 CHAR)  NOT NULL,
    punched_at  TIMESTAMP(6)      NOT NULL,
    work_date   DATE              NOT NULL,
    client_time TIMESTAMP(6),
    punch_check VARCHAR2(20 CHAR),
    source      VARCHAR2(10 CHAR) NOT NULL,
    created_by  VARCHAR2(50 CHAR) NOT NULL,
    created_at  TIMESTAMP(6)      DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_attendance_punch PRIMARY KEY (punch_id),
    CONSTRAINT fk_punch_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_punch_type CHECK (punch_type IN ('IN', 'OUT')),
    CONSTRAINT ck_punch_check CHECK (punch_check IS NULL OR punch_check IN ('DUPLICATE_IN', 'OUT_WITHOUT_IN')),
    CONSTRAINT ck_punch_check_type
        CHECK (punch_check IS NULL
            OR (punch_check = 'DUPLICATE_IN' AND punch_type = 'IN')
            OR (punch_check = 'OUT_WITHOUT_IN' AND punch_type = 'OUT')),
    CONSTRAINT ck_punch_source CHECK (source IN ('WEB')),
    CONSTRAINT ck_punch_work_date CHECK (work_date = TRUNC(work_date)),
    -- 귀속 근무일은 지금은 기록 날짜와 같다(야간 근무 귀속은 근무일정·집계 이슈에서 이 제약과 함께 바꾼다).
    CONSTRAINT ck_punch_work_date_same CHECK (work_date = TRUNC(punched_at))
);

CREATE INDEX ix_punch_emp_date ON attendance_punch (emp_id, work_date, punched_at);
