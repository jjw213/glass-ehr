-- V049 (#131): 법인별 회사 설정(docs/tenant-design.md 7장).
-- 상시근로자 수·알림 일수·주 52시간 근접 기준처럼 application.yml 한 곳에 있던 회사 설정을 법인마다 적용시작일을 가진 값으로 둔다.
-- 법정 수치가 아니다. 법정 기준값(적용 규모 하한 등)은 legal_rate 에만 둔다.
-- 법인에 값이 없으면 application.yml(glassehr.*) 값을 기본값으로 쓴다(EnterSettingService).
--
--   setting_key     EnterSettingKey 이름(WORKPLACE_REGULAR_HEADCOUNT 등). 키 목록은 코드가 정한다.
--   effective_from  적용시작일. 날짜 d 의 값 = effective_from <= d 인 행 중 가장 늦은 것(과거 날짜로 다시 판정 가능).
--   setting_value   정수 값. 키별 범위 검사는 EnterSettingService.

CREATE TABLE enter_setting (
    enter_cd        VARCHAR2(10 CHAR)  NOT NULL,
    setting_key     VARCHAR2(60 CHAR)  NOT NULL,
    effective_from  DATE               NOT NULL,
    setting_value   NUMBER(10)         NOT NULL,
    updated_by      VARCHAR2(50 CHAR)  NOT NULL,
    updated_at      TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_enter_setting PRIMARY KEY (enter_cd, setting_key, effective_from),
    CONSTRAINT fk_enter_setting_enter FOREIGN KEY (enter_cd) REFERENCES enter_company (enter_cd),
    CONSTRAINT ck_enter_setting_enter
        CHECK (REGEXP_LIKE(enter_cd, '^[A-Z0-9]+$', 'c') AND LENGTH(enter_cd) >= 2),
    CONSTRAINT ck_enter_setting_key CHECK (REGEXP_LIKE(setting_key, '^[A-Z0-9_]+$', 'c'))
);

-- 변경 이력. 등록·수정할 때마다 한 행(지우지 않는다). old_value NULL = 그 적용시작일에 새로 등록.
CREATE TABLE enter_setting_hist (
    enter_cd        VARCHAR2(10 CHAR)  NOT NULL,
    hist_id         NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    setting_key     VARCHAR2(60 CHAR)  NOT NULL,
    effective_from  DATE               NOT NULL,
    old_value       NUMBER(10),
    new_value       NUMBER(10)         NOT NULL,
    changed_by      VARCHAR2(50 CHAR)  NOT NULL,
    changed_at      TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_enter_setting_hist PRIMARY KEY (enter_cd, hist_id),
    CONSTRAINT fk_enter_setting_hist_enter FOREIGN KEY (enter_cd) REFERENCES enter_company (enter_cd),
    CONSTRAINT fk_enter_setting_hist_setting FOREIGN KEY (enter_cd, setting_key, effective_from)
        REFERENCES enter_setting (enter_cd, setting_key, effective_from),
    CONSTRAINT ck_enter_setting_hist_enter
        CHECK (REGEXP_LIKE(enter_cd, '^[A-Z0-9]+$', 'c') AND LENGTH(enter_cd) >= 2)
);

CREATE INDEX ix_enter_setting_hist_key ON enter_setting_hist (enter_cd, setting_key, changed_at);
