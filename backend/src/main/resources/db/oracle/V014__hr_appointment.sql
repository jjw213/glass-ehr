-- 인사발령 1: 발령 테이블과 발령 유형 공통코드 (#58, #16을 나눈 1번). 설계: docs/hr-appointment-design.md
--
-- 근거 (2026-11-13 law.go.kr 자동 조회가 되지 않아 원문 미확인. 사람이 원문으로 다시 확인해야 한다)
--   - 근로기준법 제23조 제1항: 사용자는 근로자에게 정당한 이유 없이 해고, 휴직, 정직, 전직, 감봉, 그 밖의 징벌을 하지 못한다.
--     → 발령마다 사유(reason)를 반드시 적는다(NOT NULL + 공백 금지).
--   - 남녀고용평등과 일·가정 양립 지원에 관한 법률 제19조: 육아휴직 → 휴직(LEAVE) 발령으로 등록하고 휴직 시작·종료 예정일을 둔다.
--
-- 이번 이슈 범위: 발령 등록·수정(미확정만)·확정·조회. 확정된 발령을 사원 정보(employee)에 반영하는 일은 다음 이슈에서 한다.
-- 발령 유형 코드값은 로직이 참조하므로 com.glassehr.appointment.AppointmentType 과 같게 유지한다(AppointmentSchemaScriptTest).
-- 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.appointment.HrAppointment (ddl-auto: validate)

-- 발령번호 순번. 형식 AP-등록연도-6자리 순번(AppointmentNoGenerator). 등록이 롤백되면 빈 번호가 생길 수 있다(번호는 식별용).
CREATE SEQUENCE hr_appointment_no_seq START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE hr_appointment (
    appt_id                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    -- 발령번호(예: AP-2026-000001)
    appt_no                 VARCHAR2(20 CHAR)   NOT NULL,
    -- 발령 유형 공통코드(APPOINTMENT_TYPE): HIRE·TRANSFER·PROMOTION·TITLE_CHANGE·LEAVE·RETURN·RETIREMENT
    appt_type_code          VARCHAR2(30 CHAR)   NOT NULL,
    -- 대상 사원
    emp_id                  NUMBER(10)          NOT NULL,
    -- 발령일(효력 발생일)
    effective_date          DATE                NOT NULL,
    -- 이전 값(등록·수정·확정 때 사원 현재 값으로 채움). 입사 발령은 모두 NULL
    before_dept_id          NUMBER(10),
    before_job_grade_code   VARCHAR2(30 CHAR),
    before_job_title_code   VARCHAR2(30 CHAR),
    before_emp_status       VARCHAR2(10 CHAR),
    -- 이후 값. 유형이 바꾸지 않는 항목은 이전 값을 그대로 옮긴다
    after_dept_id           NUMBER(10),
    after_job_grade_code    VARCHAR2(30 CHAR),
    after_job_title_code    VARCHAR2(30 CHAR),
    after_emp_status        VARCHAR2(10 CHAR)   NOT NULL,
    -- 발령 사유(근로기준법 제23조 제1항)
    reason                  VARCHAR2(1000 CHAR) NOT NULL,
    -- 휴직 시작·종료 예정일(휴직 발령만. 남녀고용평등법 제19조 육아휴직 등)
    leave_start_date        DATE,
    leave_end_date          DATE,
    -- 확정 여부·확정일시. 확정된 발령은 수정·삭제하지 않는다
    confirmed_yn            VARCHAR2(1 CHAR)    DEFAULT 'N' NOT NULL,
    confirmed_at            TIMESTAMP(6),

    created_at              TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_hr_appointment PRIMARY KEY (appt_id),
    CONSTRAINT uq_hr_appointment_no UNIQUE (appt_no),
    CONSTRAINT fk_hr_appt_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT fk_hr_appt_before_dept FOREIGN KEY (before_dept_id) REFERENCES org_dept (dept_id),
    CONSTRAINT fk_hr_appt_after_dept FOREIGN KEY (after_dept_id) REFERENCES org_dept (dept_id),
    CONSTRAINT ck_hr_appt_no
        CHECK (REGEXP_LIKE(appt_no, '^AP-[0-9][0-9][0-9][0-9]-[0-9][0-9][0-9][0-9][0-9][0-9]$', 'c')),
    CONSTRAINT ck_hr_appt_reason CHECK (TRIM(reason) IS NOT NULL),
    CONSTRAINT ck_hr_appt_before_status
        CHECK (before_emp_status IS NULL OR before_emp_status IN ('ACTIVE', 'ON_LEAVE', 'RETIRED')),
    CONSTRAINT ck_hr_appt_after_status CHECK (after_emp_status IN ('ACTIVE', 'ON_LEAVE', 'RETIRED')),
    CONSTRAINT ck_hr_appt_leave
        CHECK ((appt_type_code = 'LEAVE' AND leave_start_date IS NOT NULL AND leave_end_date IS NOT NULL
                AND leave_end_date >= leave_start_date)
            OR (appt_type_code <> 'LEAVE' AND leave_start_date IS NULL AND leave_end_date IS NULL)),
    CONSTRAINT ck_hr_appt_confirmed_yn CHECK (confirmed_yn IN ('Y', 'N')),
    CONSTRAINT ck_hr_appt_confirmed
        CHECK ((confirmed_yn = 'Y' AND confirmed_at IS NOT NULL) OR (confirmed_yn = 'N' AND confirmed_at IS NULL)),
    CONSTRAINT ck_hr_appt_date_only
        CHECK (effective_date = TRUNC(effective_date)
            AND (leave_start_date IS NULL OR leave_start_date = TRUNC(leave_start_date))
            AND (leave_end_date IS NULL OR leave_end_date = TRUNC(leave_end_date)))
);

CREATE INDEX ix_hr_appt_emp ON hr_appointment (emp_id, effective_date);
CREATE INDEX ix_hr_appt_effective ON hr_appointment (effective_date);
CREATE INDEX ix_hr_appt_before_dept ON hr_appointment (before_dept_id);
CREATE INDEX ix_hr_appt_after_dept ON hr_appointment (after_dept_id);

