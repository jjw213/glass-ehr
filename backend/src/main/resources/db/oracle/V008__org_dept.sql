-- 조직(부서) (#12). 이력은 유효기간 방식(docs/org-history-design.md, #8 결정).
-- 부서의 정체성(org_dept, dept_id 불변)과 시점별 속성(org_dept_hist)을 나눈다.
--
-- 규칙
--   - 기간은 날짜 단위 반개구간 [valid_from, valid_to). valid_to NULL = 현재 유효(종료일 미정).
--     기준일 d 조회 조건: valid_from <= d AND (valid_to IS NULL OR d < valid_to).
--   - 이력은 추가로만 쌓는다. 변경 시 마지막 행의 valid_to 를 새 행의 valid_from 과 같은 날로 닫고 새 행을 넣는다.
--     같은 부서의 기간 겹침은 서비스가 막는다(쓰기 시 테이블 잠금 + 마지막 행 뒤에만 추가). DB는 같은 시작일 중복을 막는다.
--   - 폐지는 org_dept.valid_to 와 마지막 hist 행의 valid_to 를 폐지일로 맞춘다.
--   - 상위부서(parent_dept_id)는 그 기간에 유효해야 하고, 자기 자신·자기 하위를 상위로 둘 수 없다(서비스 검사).
--   - 부서장(head_emp_id)은 사원의 불변 내부 키(emp_id, #9). 사원 테이블이 아직 없어 FK는 사원 등록 이슈에서 건다.
--   - 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.org.OrgDept, OrgDeptHist (ddl-auto: validate)

CREATE TABLE org_dept (
    dept_id       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dept_code     VARCHAR2(20 CHAR)  NOT NULL,
    valid_from    DATE               NOT NULL,
    valid_to      DATE,
    close_reason  VARCHAR2(500 CHAR),
    created_at    TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_org_dept PRIMARY KEY (dept_id),
    CONSTRAINT uq_org_dept_code UNIQUE (dept_code),
    CONSTRAINT ck_org_dept_code
        CHECK (REGEXP_LIKE(dept_code, '^[A-Z0-9][A-Z0-9_]*$', 'c')),
    CONSTRAINT ck_org_dept_period
        CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_org_dept_date_only
        CHECK (valid_from = TRUNC(valid_from) AND (valid_to IS NULL OR valid_to = TRUNC(valid_to)))
);

CREATE TABLE org_dept_hist (
    hist_id         NUMBER(12) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    dept_id         NUMBER(10)         NOT NULL,
    valid_from      DATE               NOT NULL,
    valid_to        DATE,
    dept_name       VARCHAR2(100 CHAR) NOT NULL,
    parent_dept_id  NUMBER(10),
    head_emp_id     NUMBER(10),
    sort_order      NUMBER(5)          DEFAULT 0 NOT NULL,
    change_type     VARCHAR2(10 CHAR)  NOT NULL,
    change_reason   VARCHAR2(500 CHAR),
    created_at      TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_org_dept_hist PRIMARY KEY (hist_id),
    CONSTRAINT fk_org_dept_hist_dept
        FOREIGN KEY (dept_id) REFERENCES org_dept (dept_id),
    CONSTRAINT fk_org_dept_hist_parent
        FOREIGN KEY (parent_dept_id) REFERENCES org_dept (dept_id),
    CONSTRAINT uq_org_dept_hist_start UNIQUE (dept_id, valid_from),
    CONSTRAINT ck_org_dept_hist_period
        CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT ck_org_dept_hist_date_only
        CHECK (valid_from = TRUNC(valid_from) AND (valid_to IS NULL OR valid_to = TRUNC(valid_to))),
    CONSTRAINT ck_org_dept_hist_self
        CHECK (parent_dept_id IS NULL OR parent_dept_id <> dept_id),
    CONSTRAINT ck_org_dept_hist_name
        CHECK (LENGTH(TRIM(dept_name)) > 0),
    CONSTRAINT ck_org_dept_hist_sort
        CHECK (sort_order >= 0),
    CONSTRAINT ck_org_dept_hist_type
        CHECK (change_type IN ('CREATE', 'RENAME', 'MOVE', 'UPDATE'))
);

CREATE INDEX ix_org_dept_hist_period ON org_dept_hist (valid_from, valid_to);
CREATE INDEX ix_org_dept_hist_parent ON org_dept_hist (parent_dept_id);
