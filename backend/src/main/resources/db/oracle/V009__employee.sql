-- 사원 기본정보(근로자 명부) (#14). 설계: docs/employee-design.md
--
-- 근거
--   - 근로기준법 제41조(근로자 명부), 같은 법 시행령 제20조(명부 기재사항):
--     성명, 성별, 생년월일, 주소, 이력, 종사하는 업무의 종류, 고용·고용갱신 연월일과 계약기간·그 밖의 고용에 관한 사항,
--     해고·퇴직·사망 연월일과 사유, 그 밖에 필요한 사항 (이슈 #14 본문의 목록. 컬럼 대응은 아래 주석)
--   - 근로기준법 제42조(계약 서류의 보존): 보존 기간은 legal_rate 항목 EMPLOYEE_RECORD_RETENTION_YEARS(V010)에서 읽는다.
--   - 개인정보 보호법 제24조의2·제29조: 주민등록번호는 employee 에 두지 않고 emp_rrn 에 암호문으로만 둔다(docs/rrn-design.md).
--
-- 규칙
--   - emp_id 는 불변 내부 키(#9). 다른 테이블은 emp_id 로 참조한다. 사번(emp_no)은 S01-2026-001 형식(#9 결정).
--   - 현재 소속(current_dept_id)·직급(job_grade_code)·직책(job_title_code)은 인사발령 결과로만 바뀐다.
--     사원 정보 수정 API는 이 컬럼을 받지 않는다(입사 등록 시 첫 값만 넣음).
--   - 정규식에 중괄호를 쓰지 않는다(Oracle JDBC SQL92 escape 문제, V006 참고).
-- JPA 엔티티: com.glassehr.employee.* (ddl-auto: validate)

-- 사업장. 사번 앞부분(사업장코드)의 출처(docs/employee-number-design.md 1장).
-- 근무지 공통코드(WORK_LOCATION)와 별개로 둔다. 사업장 추가는 마이그레이션으로 한다(관리 화면은 후속 이슈).
CREATE TABLE biz_site (
    site_code   VARCHAR2(3 CHAR)   NOT NULL,
    site_name   VARCHAR2(100 CHAR) NOT NULL,
    use_yn      VARCHAR2(1 CHAR)   DEFAULT 'Y' NOT NULL,
    created_at  TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_biz_site PRIMARY KEY (site_code),
    CONSTRAINT ck_biz_site_code CHECK (REGEXP_LIKE(site_code, '^S[0-9][0-9]$', 'c')),
    CONSTRAINT ck_biz_site_name CHECK (LENGTH(TRIM(site_name)) > 0),
    CONSTRAINT ck_biz_site_use_yn CHECK (use_yn IN ('Y', 'N'))
);

-- 예시 사업장(가짜 이름). 회사가 실제 사업장으로 고친다.
INSERT INTO biz_site (site_code, site_name) VALUES ('S01', '본사 사업장(예시)');

-- 사번 채번. 사업장·입사연도마다 순번을 001부터 다시 매긴다(#9). 등록 트랜잭션 안에서 행을 잠그고 last_seq + 1.
CREATE TABLE emp_no_seq (
    site_code   VARCHAR2(3 CHAR)  NOT NULL,
    hire_year   NUMBER(4)         NOT NULL,
    last_seq    NUMBER(3)         NOT NULL,

    CONSTRAINT pk_emp_no_seq PRIMARY KEY (site_code, hire_year),
    CONSTRAINT fk_emp_no_seq_site FOREIGN KEY (site_code) REFERENCES biz_site (site_code),
    CONSTRAINT ck_emp_no_seq_range CHECK (last_seq BETWEEN 1 AND 999)
);

CREATE TABLE employee (
    emp_id                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_no                  VARCHAR2(12 CHAR)   NOT NULL,
    site_code               VARCHAR2(3 CHAR)    NOT NULL,

    -- 시행령 제20조: 성명·성별·생년월일·주소
    emp_name                VARCHAR2(100 CHAR)  NOT NULL,
    gender                  VARCHAR2(1 CHAR)    NOT NULL,
    birth_date              DATE                NOT NULL,
    address                 VARCHAR2(300 CHAR)  NOT NULL,
    -- 시행령 제20조: 이력(학력·경력 등 자유 기재)
    career_history          VARCHAR2(4000 CHAR),
    -- 시행령 제20조: 종사하는 업무의 종류
    job_description         VARCHAR2(500 CHAR)  NOT NULL,
    job_family_code         VARCHAR2(30 CHAR),
    -- 시행령 제20조: 고용 또는 고용갱신 연월일, 계약기간(정한 경우), 그 밖의 고용에 관한 사항
    hire_date               DATE                NOT NULL,
    renewal_date            DATE,
    contract_start_date     DATE,
    contract_end_date       DATE,
    employment_type_code    VARCHAR2(30 CHAR)   NOT NULL,
    weekly_contract_minutes NUMBER(5),
    work_location_code      VARCHAR2(30 CHAR),
    employment_note         VARCHAR2(1000 CHAR),
    -- 현재 소속·직급·직책: 인사발령 결과로만 바뀜
    current_dept_id         NUMBER(10),
    job_grade_code          VARCHAR2(30 CHAR),
    job_title_code          VARCHAR2(30 CHAR),
    -- 시행령 제20조: 해고·퇴직·사망한 경우 그 연월일과 사유 (사유 구분은 공통코드 RETIREMENT_REASON, 사망 포함)
    retire_date             DATE,
    retire_reason_code      VARCHAR2(30 CHAR),
    retire_reason_detail    VARCHAR2(1000 CHAR),
    -- 근로기준법 제42조: 퇴직일 + legal_rate EMPLOYEE_RECORD_RETENTION_YEARS(퇴직일 기준 적용값)
    record_retention_until  DATE,
    -- 시행령 제20조: 그 밖에 필요한 사항
    other_note              VARCHAR2(1000 CHAR),

    created_at              TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_employee PRIMARY KEY (emp_id),
    CONSTRAINT uq_employee_emp_no UNIQUE (emp_no),
    CONSTRAINT fk_employee_site FOREIGN KEY (site_code) REFERENCES biz_site (site_code),
    CONSTRAINT fk_employee_dept FOREIGN KEY (current_dept_id) REFERENCES org_dept (dept_id),
    CONSTRAINT ck_employee_emp_no
        CHECK (REGEXP_LIKE(emp_no, '^S[0-9][0-9]-[0-9][0-9][0-9][0-9]-[0-9][0-9][0-9]$', 'c')),
    CONSTRAINT ck_employee_emp_no_site CHECK (SUBSTR(emp_no, 1, 3) = site_code),
    CONSTRAINT ck_employee_name CHECK (LENGTH(TRIM(emp_name)) > 0),
    CONSTRAINT ck_employee_gender CHECK (gender IN ('M', 'F')),
    CONSTRAINT ck_employee_job_desc CHECK (LENGTH(TRIM(job_description)) > 0),
    CONSTRAINT ck_employee_minutes CHECK (weekly_contract_minutes IS NULL OR weekly_contract_minutes > 0),
    CONSTRAINT ck_employee_contract
        CHECK (contract_end_date IS NULL OR contract_start_date IS NULL OR contract_end_date >= contract_start_date),
    CONSTRAINT ck_employee_contract_end_start
        CHECK (contract_end_date IS NULL OR contract_start_date IS NOT NULL),
    CONSTRAINT ck_employee_renewal CHECK (renewal_date IS NULL OR renewal_date >= hire_date),
    CONSTRAINT ck_employee_retire
        CHECK ((retire_date IS NULL AND retire_reason_code IS NULL AND record_retention_until IS NULL)
            OR (retire_date IS NOT NULL AND retire_reason_code IS NOT NULL AND record_retention_until IS NOT NULL)),
    CONSTRAINT ck_employee_retire_after_hire CHECK (retire_date IS NULL OR retire_date >= hire_date),
    CONSTRAINT ck_employee_retention CHECK (record_retention_until IS NULL OR record_retention_until > retire_date),
    CONSTRAINT ck_employee_date_only
        CHECK (birth_date = TRUNC(birth_date) AND hire_date = TRUNC(hire_date)
            AND (renewal_date IS NULL OR renewal_date = TRUNC(renewal_date))
            AND (contract_start_date IS NULL OR contract_start_date = TRUNC(contract_start_date))
            AND (contract_end_date IS NULL OR contract_end_date = TRUNC(contract_end_date))
            AND (retire_date IS NULL OR retire_date = TRUNC(retire_date))
            AND (record_retention_until IS NULL OR record_retention_until = TRUNC(record_retention_until)))
);

CREATE INDEX ix_employee_dept ON employee (current_dept_id);
CREATE INDEX ix_employee_retention ON employee (record_retention_until);

-- 부서장(org_dept_hist.head_emp_id)은 사원 테이블이 생기면 FK 를 건다(V008 주석).
ALTER TABLE org_dept_hist ADD CONSTRAINT fk_org_dept_hist_head
    FOREIGN KEY (head_emp_id) REFERENCES employee (emp_id);

-- 주민등록번호(외국인등록번호 포함). 평문 컬럼은 두지 않는다(docs/rrn-design.md 2장).
--   rrn_enc    AES-256-GCM 암호문(앞 12바이트 IV + 암호문 + 16바이트 태그). 애플리케이션에서 암호화한다.
--   rrn_masked 화면 표시용. 앞 6자리만 보이고 뒷자리 7자리는 모두 가린다(예: 000000-*******).
--   rrn_hash   중복 등록 검사용 HMAC-SHA256(암호화 키와 다른 키). 원문 복원 불가.
CREATE TABLE emp_rrn (
    emp_id       NUMBER(10)          NOT NULL,
    rrn_enc      RAW(64)             NOT NULL,
    rrn_masked   VARCHAR2(14 CHAR)   NOT NULL,
    rrn_hash     RAW(32)             NOT NULL,
    key_version  NUMBER(3)           NOT NULL,
    created_at   TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at   TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by   VARCHAR2(50 CHAR)   NOT NULL,

    CONSTRAINT pk_emp_rrn PRIMARY KEY (emp_id),
    CONSTRAINT fk_emp_rrn_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT uq_emp_rrn_hash UNIQUE (rrn_hash),
    CONSTRAINT ck_emp_rrn_masked CHECK (REGEXP_LIKE(rrn_masked, '^[0-9][0-9][0-9][0-9][0-9][0-9]-[*][*][*][*][*][*][*]$', 'c')),
    CONSTRAINT ck_emp_rrn_key_version CHECK (key_version >= 1)
);

-- 주민등록번호 원문 조회 로그. 추가만 한다(애플리케이션은 INSERT·SELECT만, 엔티티는 @Immutable).
-- 원문·마스킹 값은 남기지 않는다(emp_id 만).
CREATE TABLE rrn_access_log (
    log_id        NUMBER(15) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    accessor_id   VARCHAR2(50 CHAR)   NOT NULL,
    accessor_role VARCHAR2(20 CHAR),
    emp_id        NUMBER(10)          NOT NULL,
    accessed_at   TIMESTAMP(6)        NOT NULL,
    purpose_code  VARCHAR2(20 CHAR)   NOT NULL,
    client_ip     VARCHAR2(45 CHAR),
    result        VARCHAR2(10 CHAR)   NOT NULL,

    CONSTRAINT pk_rrn_access_log PRIMARY KEY (log_id),
    CONSTRAINT ck_rrn_access_log_purpose CHECK (purpose_code IN ('VIEW', 'SOCIAL_INSURANCE', 'WITHHOLDING')),
    CONSTRAINT ck_rrn_access_log_result CHECK (result IN ('SUCCESS', 'DENIED', 'NOT_FOUND'))
);

CREATE INDEX ix_rrn_access_log_emp ON rrn_access_log (emp_id, accessed_at);
