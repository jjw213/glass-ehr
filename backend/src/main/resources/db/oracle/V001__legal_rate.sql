-- 법령 기준값 테이블 (#3). 설계: docs/legal-rate-design.md
-- 최저임금(최저임금법), 4대보험 요율(국민연금법, 국민건강보험법,
-- 고용보험 및 산업재해보상보험의 보험료징수 등에 관한 법률), 비과세 한도(소득세법) 등
-- 해마다 바뀌는 값을 적용시작일 기준으로 저장한다. 코드에는 수치를 쓰지 않는다.
--
-- 기간 규칙: 시작일 포함, 종료일 제외 [effective_from, effective_to). effective_to NULL = 종료 미정.
-- 날짜는 Asia/Seoul 기준 달력 날짜이며 시각 성분을 갖지 않는다.

CREATE TABLE legal_rate_item (
    item_code       VARCHAR2(64 CHAR)  NOT NULL,
    item_name       VARCHAR2(200 CHAR) NOT NULL,
    CONSTRAINT pk_legal_rate_item PRIMARY KEY (item_code)
);

CREATE TABLE legal_rate (
    legal_rate_id   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    item_code       VARCHAR2(64 CHAR)   NOT NULL,
    effective_from  DATE                NOT NULL,
    effective_to    DATE,
    rate_value      NUMBER(18, 6)       NOT NULL,
    unit            VARCHAR2(32 CHAR)   NOT NULL,
    legal_basis     VARCHAR2(1000 CHAR) NOT NULL,
    source_url      VARCHAR2(2000 CHAR) NOT NULL,
    created_at      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by      VARCHAR2(100 CHAR)  NOT NULL,

    CONSTRAINT pk_legal_rate PRIMARY KEY (legal_rate_id),
    CONSTRAINT fk_legal_rate_item
        FOREIGN KEY (item_code) REFERENCES legal_rate_item (item_code),
    CONSTRAINT ck_legal_rate_date_only
        CHECK (effective_from = TRUNC(effective_from)
           AND (effective_to IS NULL OR effective_to = TRUNC(effective_to))),
    CONSTRAINT ck_legal_rate_period
        CHECK (effective_to IS NULL OR effective_from < effective_to),
    CONSTRAINT ck_legal_rate_unit
        CHECK (LENGTH(TRIM(unit)) > 0),
    CONSTRAINT ck_legal_rate_basis
        CHECK (LENGTH(TRIM(legal_basis)) > 0),
    CONSTRAINT ck_legal_rate_url
        CHECK (LENGTH(TRIM(source_url)) > 0),
    CONSTRAINT uq_legal_rate_item_from UNIQUE (item_code, effective_from)
);

CREATE INDEX ix_legal_rate_item_period
    ON legal_rate (item_code, effective_from, effective_to);
