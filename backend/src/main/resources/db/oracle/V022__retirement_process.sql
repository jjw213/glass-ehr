CREATE TABLE retirement_case (
    case_id               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id                NUMBER(10)          NOT NULL,
    retire_reason_code    VARCHAR2(30 CHAR)   NOT NULL,
    retire_date           DATE                NOT NULL,
    -- 근로기준법 제26조: 해고 예고일(해고일 때만)
    dismissal_notice_date DATE,
    -- 근로기준법 제27조: 해고사유·해고시기를 적은 서면 통지일(해고일 때만)
    written_notice_date   DATE,
    -- 근로기준법 제26조 단서: 예고 적용 제외 사유(SHORT_SERVICE 제1호, UNAVOIDABLE 제2호, EMPLOYEE_FAULT 제3호)
    notice_exempt_code    VARCHAR2(20 CHAR),
    -- 등록 당시 예고 확인 결과: NOT_APPLICABLE(해고 아님)·OK·SHORT(미달)·EXEMPT(적용 제외)·UNKNOWN(기준값 없음)
    notice_check          VARCHAR2(20 CHAR)   NOT NULL,
    notice_days           NUMBER(5),
    notice_shortfall_days NUMBER(5),
    created_by            VARCHAR2(50 CHAR)   NOT NULL,
    created_at            TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_retirement_case PRIMARY KEY (case_id),
    CONSTRAINT uq_retirement_case_emp UNIQUE (emp_id),
    CONSTRAINT fk_retirement_case_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_retirement_dismissal
        CHECK (retire_reason_code <> 'DISMISSAL'
            OR (dismissal_notice_date IS NOT NULL AND written_notice_date IS NOT NULL)),
    CONSTRAINT ck_retirement_notice_only_dismissal
        CHECK (retire_reason_code = 'DISMISSAL'
            OR (dismissal_notice_date IS NULL AND written_notice_date IS NULL AND notice_exempt_code IS NULL)),
    CONSTRAINT ck_retirement_notice_before
        CHECK (dismissal_notice_date IS NULL OR dismissal_notice_date <= retire_date),
    CONSTRAINT ck_retirement_written_before
        CHECK (written_notice_date IS NULL OR written_notice_date <= retire_date),
    CONSTRAINT ck_retirement_exempt
        CHECK (notice_exempt_code IS NULL OR notice_exempt_code IN ('SHORT_SERVICE', 'UNAVOIDABLE', 'EMPLOYEE_FAULT')),
    CONSTRAINT ck_retirement_notice_check
        CHECK (notice_check IN ('NOT_APPLICABLE', 'OK', 'SHORT', 'EXEMPT', 'UNKNOWN')),
    CONSTRAINT ck_retirement_notice_check_type
        CHECK ((retire_reason_code = 'DISMISSAL' AND notice_check <> 'NOT_APPLICABLE')
            OR (retire_reason_code <> 'DISMISSAL' AND notice_check = 'NOT_APPLICABLE')),
    CONSTRAINT ck_retirement_shortfall
        CHECK (notice_shortfall_days IS NULL OR (notice_check = 'SHORT' AND notice_shortfall_days > 0)),
    CONSTRAINT ck_retirement_date_only
        CHECK (retire_date = TRUNC(retire_date)
            AND (dismissal_notice_date IS NULL OR dismissal_notice_date = TRUNC(dismissal_notice_date))
            AND (written_notice_date IS NULL OR written_notice_date = TRUNC(written_notice_date)))
);

CREATE TABLE retirement_checklist_item (
    case_id     NUMBER(10)          NOT NULL,
    item_code   VARCHAR2(30 CHAR)   NOT NULL,
    sort_order  NUMBER(5)           NOT NULL,
    label       VARCHAR2(200 CHAR)  NOT NULL,
    legal_basis VARCHAR2(200 CHAR),
    done_at     TIMESTAMP(6),
    done_by     VARCHAR2(50 CHAR),
    note        VARCHAR2(500 CHAR),

    CONSTRAINT pk_retirement_checklist PRIMARY KEY (case_id, item_code),
    CONSTRAINT fk_retirement_checklist_case FOREIGN KEY (case_id) REFERENCES retirement_case (case_id),
    CONSTRAINT ck_retirement_checklist_done
        CHECK ((done_at IS NULL AND done_by IS NULL) OR (done_at IS NOT NULL AND done_by IS NOT NULL))
);

CREATE TABLE employment_certificate (
    cert_id          NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    emp_id           NUMBER(10)          NOT NULL,
    requested_on     DATE                NOT NULL,
    -- 근로자가 요구한 항목(쉼표 구분): USE_PERIOD, JOB_TYPE, POSITION, WAGE, RETIRE_REASON
    requested_items  VARCHAR2(200 CHAR)  NOT NULL,
    purpose          VARCHAR2(200 CHAR),
    -- 발급 당시 기재 값. 요구하지 않은 항목은 비워 둔다(근로기준법 제39조 제2항).
    emp_name         VARCHAR2(100 CHAR)  NOT NULL,
    use_from         DATE,
    use_to           DATE,
    job_type         VARCHAR2(1000 CHAR),
    position_text    VARCHAR2(200 CHAR),
    wage_amount      NUMBER(15),
    wage_unit_code   VARCHAR2(10 CHAR),
    retire_reason    VARCHAR2(200 CHAR),
    issued_by        VARCHAR2(50 CHAR)   NOT NULL,
    issued_at        TIMESTAMP(6)        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_employment_certificate PRIMARY KEY (cert_id),
    CONSTRAINT fk_employment_cert_emp FOREIGN KEY (emp_id) REFERENCES employee (emp_id),
    CONSTRAINT ck_employment_cert_items CHECK (TRIM(requested_items) IS NOT NULL),
    CONSTRAINT ck_employment_cert_use
        CHECK ((use_from IS NULL AND use_to IS NULL) OR use_from IS NOT NULL),
    CONSTRAINT ck_employment_cert_wage CHECK (wage_amount IS NULL OR wage_amount >= 0),
    CONSTRAINT ck_employment_cert_date_only
        CHECK (requested_on = TRUNC(requested_on)
            AND (use_from IS NULL OR use_from = TRUNC(use_from))
            AND (use_to IS NULL OR use_to = TRUNC(use_to)))
);

CREATE INDEX ix_employment_cert_emp ON employment_certificate (emp_id, issued_at);
